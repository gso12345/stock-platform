"""안 되는 곳은 쉬게 하고, 가끔만 다시 찔러본다.

같은 것을 네 번째 쓴다 — 뉴스 피드, 국내 지수, 그리고 이번에 국내 금리
두 군데. 그때마다 `_연속실패` 딕셔너리와 `_쉼_기준` 상수를 새로 만들었고,
이름만 조금씩 달라서 관리자 화면에서 꺼내 볼 때도 세 벌을 따로 알아야 했다.

규칙 자체는 한 줄이다:

    연속으로 N번 실패한 이름은 그만 물어본다. 다만 목록에서 지우지는
    않고, 가끔 한 번씩 다시 찔러본다. 되살아나면 스스로 돌아온다.

지우지 않는 것이 요점이다. 지우면 원천이 되살아나도 사람이 알아채고
코드를 고치기 전까지는 영영 안 온다. 쉬게만 두면 얼마 뒤 저절로
돌아온다. 덕분에 '맞는지 모르는 후보' 를 목록에 넣어 보는 값이 거의
0 이 된다 — 되면 얻고, 안 되면 몇 분 만에 스스로 빠진다.

다시 찔러보는 방식은 두 가지를 담았다.

  · 돌아가며_깨우기 — 회차마다 쉬는 것 중 몇 칸만 깨운다. 후보가 많은
    곳에 쓴다. 한 회차 비용이 칸 수만큼으로 고정되고, 모든 후보가 같은
    빈도로 돌아온다.
  · 찔러볼때인가 — N회차마다 한 번 전부 깨운다. 후보가 서넛뿐이라
    한꺼번에 깨워도 부담이 없는 곳에 쓴다.

앞의 것이 기본이다. 뒤의 것을 큰 목록에 쓰면 '깨우는 회차' 하나가
통째로 비싸지고, 그 회차에 중간에 끊기면 목록 뒷부분은 영영 안 깨어난다.
"""
import threading


class 쉼표:
    """이름별 연속 실패를 세고, 쉴 때가 됐는지 알려준다.

    스레드 여러 개가 같이 쓴다(뉴스는 ThreadPoolExecutor 에서 부른다).
    dict 갱신 자체는 GIL 덕에 깨지지 않지만 `읽고-더하고-쓰기` 는 아니라
    자물쇠를 둔다 — 세는 값이 한둘 어긋나도 큰일은 아니지만, 굳이
    어긋날 이유도 없다.
    """

    def __init__(self, 쉼_기준: int = 5, 되살림_칸: int = 1,
                 되살림_주기: int = 60):
        #: 이만큼 연속 실패하면 쉬는 것으로 본다. 한두 번은 상대 서버가
        #: 잠깐 흔들린 것일 수 있어 넉넉히 잡는다.
        self.쉼_기준 = max(1, 쉼_기준)
        #: 한 회차에 다시 찔러볼 칸 수 (돌아가며_깨우기)
        self.되살림_칸 = max(0, 되살림_칸)
        #: 몇 회차마다 전부 찔러볼지 (찔러볼때인가)
        self.되살림_주기 = max(1, 되살림_주기)
        self._연속실패: dict[str, int] = {}
        self._회차 = 0
        self._깨울자리 = 0
        self._자물쇠 = threading.Lock()

    # ── 상태 ────────────────────────────────────────────────
    def 쉬는가(self, 이름: str) -> bool:
        return self._연속실패.get(이름, 0) >= self.쉼_기준

    def 기록(self, 이름: str, 실패했나: bool) -> None:
        with self._자물쇠:
            if 실패했나:
                self._연속실패[이름] = self._연속실패.get(이름, 0) + 1
            else:
                self._연속실패[이름] = 0

    def 실패수(self, 이름: str) -> int:
        return self._연속실패.get(이름, 0)

    def 쉬는것들(self) -> list:
        """관리자 화면용 — 지금 쉬고 있는 이름들."""
        return sorted(n for n, c in self._연속실패.items() if c >= self.쉼_기준)

    def 잊기(self, 이름=None) -> None:
        with self._자물쇠:
            if 이름 is None:
                self._연속실패.clear()
                self._회차 = 0
                self._깨울자리 = 0
            else:
                self._연속실패.pop(이름, None)

    # ── 고르기 ──────────────────────────────────────────────
    def 돌아가며_깨우기(self, 전체: list, 이름꺼내기=None) -> list:
        """쉬지 않는 것 전부 + 쉬는 것 중 몇 칸(회차마다 자리를 옮겨 가며).

        한 회차의 비용이 '살아 있는 수 + 되살림_칸' 으로 고정된다.
        되살림 회차만 유독 비싸지는 일이 없고, 쉬는 것이 몇 개든 모두
        같은 빈도로 다시 시도된다 — 쉬는 것이 50개고 칸이 1이면 한
        바퀴에 50회차가 걸리지만, 어느 것도 빠지지 않는다.

        한 번 부르면 한 회차다. 한 번 갱신하면서 여러 번 부르지 말고,
        후보를 한 목록으로 모아서 한 번만 불러야 뜻대로 돈다.
        """
        꺼내기 = 이름꺼내기 or (lambda x: x)
        사는것 = [x for x in 전체 if not self.쉬는가(꺼내기(x))]
        쉬는것 = [x for x in 전체 if self.쉬는가(꺼내기(x))]
        if not 쉬는것:
            with self._자물쇠:
                self._회차 += 1
            return 사는것

        칸 = min(self.되살림_칸, len(쉬는것))
        with self._자물쇠:
            self._회차 += 1
            시작 = self._깨울자리 % len(쉬는것)
            self._깨울자리 = (시작 + 칸) % len(쉬는것) if 칸 else 시작
        깨울것 = (쉬는것 + 쉬는것)[시작:시작 + 칸]

        # 전부 쉬는 중이고 깨울 칸도 없으면 아무것도 안 나간다. 그러면
        # 되살아날 길까지 막히므로 하나는 남긴다.
        return (사는것 + 깨울것) or 쉬는것[:1]

    def 찔러볼때인가(self) -> bool:
        """회차를 하나 올리고, 이번이 '전부 깨우는' 회차인지 알려준다."""
        with self._자물쇠:
            self._회차 += 1
            return self._회차 % self.되살림_주기 == 0

    def 골라내기(self, 전체: list, 이름꺼내기=None) -> list:
        """주기형 — N회차마다 전부 깨운다. 후보가 적은 곳에서 쓴다.

        전부 쉬는 중이면 그래도 하나는 남긴다.
        """
        꺼내기 = 이름꺼내기 or (lambda x: x)
        찔러볼때 = self.찔러볼때인가()
        고른것 = [x for x in 전체 if not self.쉬는가(꺼내기(x)) or 찔러볼때]
        return 고른것 or list(전체[:1])
