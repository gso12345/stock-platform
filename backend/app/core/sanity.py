"""
값이 이상하면 알아채는 자리.

'못 가져왔다'는 이제 기록된다(뉴스 실패 이유, 지수별 원천). 그런데 더
무서운 쪽은 **가져왔는데 값이 틀린** 경우다. 실제로 겪은 것들 —

  · 원/100엔이 1엔당 값(9.32원)으로 몇 달 동안 떠 있었다. 이름은
    '원/100엔' 인데 값은 100배 작았다. 아무 오류도 안 났다.
  · 코스닥150이 0 으로 떠 있었다. 조회는 '성공' 이었다.
  · 어떤 원천이 어제 값을 계속 돌려주는데 화면은 오늘 값인 줄 안다.

금융 화면에서 틀린 숫자는 없는 것보다 나쁘다. 없으면 사람이 다른 데서
찾아보지만, 틀린 값은 그대로 믿는다.

여기서 보는 것은 세 가지뿐이다.
  1) 상식 범위를 벗어났는가 (원/달러가 50원일 수는 없다)
  2) 0 이거나 없는가
  3) 멈춰 있는가 (어제와 소수점까지 똑같은 값)

값을 고치지는 않는다. 고칠 수 있으면 애초에 이상한 게 아니다.
기록만 남기고, 관리자 화면에서 보이게 한다.
"""
from __future__ import annotations

import logging

from app.core import health

log = logging.getLogger(__name__)

#: 이름 → (최솟값, 최댓값). 넉넉하게 잡는다 — 좁게 잡으면 멀쩡한 값이
#: 걸려서 아무도 안 보게 된다. 잡으려는 것은 '자릿수가 틀린 값' 이다.
정상범위: dict[str, tuple[float, float]] = {
    # 환율 — 100엔당과 1엔당이 100배 차이라 이 범위로 갈린다
    "원/달러":     (500, 3000),
    "원/달러 환율": (500, 3000),
    "원/유로":     (700, 4000),
    "원/유로 환율": (700, 4000),
    "원/100엔":    (300, 3000),
    # 금리 — 마이너스 금리도 있었으므로 아래는 넉넉히
    "한국 기준금리": (-1, 20),
    "CD금리(91일)": (-1, 20),
    "국고채 3년":   (-1, 20),
    "국고채 5년":   (-1, 20),
    "국고채 10년":  (-1, 20),
    # 변동성
    "VKOSPI":     (5, 100),
}

#: 지수는 이름이 아니라 종류로 본다
지수범위: dict[str, tuple[float, float]] = {
    "KOSPI":     (500, 10000),
    "KOSDAQ":    (200, 5000),
    "KOSPI200":  (50, 2000),
    "KOSDAQ150": (200, 5000),
    "SP500":     (500, 30000),
    "NASDAQ":    (1000, 100000),
    "DOW":       (5000, 200000),
    "SOX":       (500, 50000),
    "RUSSELL":   (200, 20000),
}


def _판정(이름: str, 값, 범위: tuple[float, float] | None) -> str | None:
    """이상하면 사람이 읽는 한 문장을, 멀쩡하면 None 을 돌려준다."""
    if 값 is None:
        return "값이 없음"
    try:
        v = float(값)
    except (TypeError, ValueError):
        return f"숫자가 아님 ({값!r})"
    if v == 0:
        return "0 (조회는 성공했지만 값이 비어 있음)"
    if 범위 and not (범위[0] <= v <= 범위[1]):
        return f"{v:,.4g} — 정상 범위({범위[0]:,g}~{범위[1]:,g}) 밖. 단위가 어긋났을 수 있음"
    return None


def 확인(구분: str, 이름: str, 값, 범위: tuple[float, float] | None = None) -> bool:
    """값 하나를 본다. 이상하면 기록을 남기고 False.

    구분은 관리자 화면에서 묶어 보기 위한 앞머리다("환율", "지수").
    """
    문제 = _판정(이름, 값, 범위)
    표시 = f"값:{구분}:{이름}"
    if 문제:
        health.record_fail(표시, 문제)
        log.warning("이상값 %s %s — %s", 구분, 이름, 문제)
        return False
    health.record_ok(표시, None, f"{float(값):,.4g}")
    return True


def 환율금리_확인(항목들: list[dict]) -> int:
    """대시보드에 나가는 환율·금리·변동성 목록을 훑는다.

    이름을 모르는 항목은 0 인지만 본다 — 범위를 모른다고 그냥 넘기면
    새로 추가한 지표가 검사에서 빠진다."""
    이상 = 0
    for it in 항목들 or []:
        if not isinstance(it, dict):
            continue
        이름 = it.get("name") or "이름없음"
        if not 확인("환율금리", 이름, it.get("value"), 정상범위.get(이름)):
            이상 += 1
    return 이상


def 지수_확인(항목들: list[dict]) -> int:
    """지수 목록을 훑는다. 코스닥150 이 0 으로 떠 있던 자리다."""
    이상 = 0
    for it in 항목들 or []:
        if not isinstance(it, dict):
            continue
        키 = it.get("index") or it.get("name") or "이름없음"
        if not 확인("지수", 키, it.get("value"), 지수범위.get(키)):
            이상 += 1
    return 이상


#: 값이 몇 번 연속 그대로인지 (이름 → [마지막값, 몇 번째])
_멈춤: dict[str, list] = {}

#: 이만큼 연속 같으면 멈춘 것으로 본다.
#: 장 마감 뒤에는 값이 안 변하는 게 정상이라 넉넉히 잡는다.
멈춤_기준 = 30


def 움직이는지_확인(이름: str, 값) -> bool:
    """어제 값을 계속 돌려주는 원천을 잡는다.

    조회는 성공하고 범위도 정상이라 다른 검사로는 안 걸린다. 그런데
    소수점까지 똑같은 값이 계속 오면 그건 갱신이 멈춘 것이다."""
    try:
        v = float(값)
    except (TypeError, ValueError):
        return True
    앞 = _멈춤.get(이름)
    if 앞 and 앞[0] == v:
        앞[1] += 1
        if 앞[1] == 멈춤_기준:          # 한 번만 알린다
            health.record_fail(f"값:멈춤:{이름}",
                               f"{멈춤_기준}번 연속 같은 값({v:,.4g}) — 갱신이 멈췄을 수 있음")
            log.warning("멈춘 값 %s = %s (%d회 연속)", 이름, v, 앞[1])
        return 앞[1] < 멈춤_기준
    _멈춤[이름] = [v, 1]
    return True


def 비우기() -> None:
    _멈춤.clear()
