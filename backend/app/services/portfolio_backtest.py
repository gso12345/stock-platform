"""자산배분 백테스트 — '이렇게 굴렸으면 어떻게 됐을까'.

── 지금까지의 백테스트와 무엇이 다른가 ──────────────────────

backtest_engine.py 는 **한 종목**에 **매매 신호**(RSI < 30 에 사고 …)를
걸어 보는 것이다. 이 파일은 다른 질문에 답한다 —

    "S&P500 60% · 금 20% · 현금 20% 로 8년 굴리면서
     매달 50만원씩 더 넣고 해마다 비중을 맞췄으면?"

지표도 신호도 없다. 대신 **여러 자산·비중·적립·리밸런싱**이 있다.
보통 사람이 실제로 하는 투자에 훨씬 가깝고, 신호 백테스트가 안고 있는
'미래를 엿봤나' 같은 문제도 대부분 없다.

── 적립식이면 수익률을 어떻게 재야 하나 ─────────────────────

여기가 이 파일에서 제일 중요한 자리다.

매달 넣는 사람에게 `(최종 - 초기) / 초기` 는 **완전히 틀린 수**다.
1,000만원으로 시작해 8년간 매달 50만원씩 넣으면 원금만 5,800만원이다.
최종 7,000만원일 때 '초기 대비 600%' 라고 적으면 새빨간 거짓말이다.

그래서 셋을 **따로** 낸다. 하나로 뭉치면 반드시 누군가를 속인다.

  · 총납입      실제로 넣은 돈의 합 (초기 + 적립 전부)
  · 최종평가액  마지막 날 값
  · 총수익률    (최종 - 총납입) / 총납입 — 내 돈 대비 얼마나 불었나

연환산은 **두 가지**를 낸다. 둘은 다른 질문에 답하고, 적립식에서는
값이 꽤 벌어진다.

  · TWR(시간가중)  넣고 뺀 시점의 영향을 지운 값.
                   **전략끼리 비교**할 때 쓴다. 벤치마크와 견주는 수다.
  · IRR(금액가중)  내가 실제로 번 연 수익률.
                   늦게 넣은 돈은 굴린 기간이 짧다는 것이 반영된다.

상승장에서 계속 넣었으면 IRR < TWR 이다. 늦게 넣은 돈이 덜 굴었으니까.
하락장에서 계속 넣었으면 반대다. 둘 중 하나만 보여 주면 그 차이가
통째로 사라진다.

── 현실에 가깝게 하려고 지킨 것 ─────────────────────────────

· **통화를 맞춘다.** 원화로 보는 사람에게 미국 주식은 '주가 × 환율'
  이다. 환율을 무시하면 2022년처럼 환율이 20% 오른 해의 결과가
  통째로 틀린다. 한국 투자자에게 이건 작은 항이 아니다.
· **배당을 재투자한다**(총수익 켤 때). S&P500 을 30년 굴리면 배당
  재투자 여부로 최종 금액이 두 배 가까이 갈린다.
· **자산마다 자료가 시작하는 날이 다르다.** 겹치는 구간만 쓰고,
  실제로 언제부터 쟀는지 응답에 적는다. 조용히 짧게 재면 사용자는
  8년을 잰 줄 안다.
· **현금 자산**은 시세가 없다. 값이 안 변하는 것으로 둔다 — 이자를
  지어내지 않는다.

· **거래비용을 뺀다.** 자산배분은 사고파는 횟수가 적어(연 1~4회
  리밸런싱) 신호 매매보다 영향이 훨씬 작지만 0 은 아니다. 30년을
  돌리면 0.1% 짜리 수수료도 최종 금액을 몇 %씩 갉는다. 살 때·팔 때
  모두 매긴다 — 리밸런싱은 판 만큼 사는 것이라 양쪽에 다 붙는다.
"""
from __future__ import annotations

import logging
from datetime import date, datetime, timedelta
from typing import Optional

log = logging.getLogger(__name__)

#: 적립·리밸런싱 주기. 화면의 드롭다운과 같은 값이다.
주기들 = ("none", "monthly", "quarterly", "yearly")

#: 현금처럼 시세가 없는 자산. 값이 안 변하는 것으로 둔다.
현금류 = {"현금", "CASH", "예금"}

#: 한 번에 담을 수 있는 자산 수. 자산배분은 보통 2~8개다.
#  많아질수록 받아야 할 시세도 늘어 0.15 CPU 서버에 부담이 된다.
최대자산 = 12


def 정규화(자산들: list[dict]) -> list[dict]:
    """비중을 합이 1이 되게 고친다.

    화면에서 60/20/20 을 넣으면 합이 100 이고, 0.6/0.2/0.2 를 넣으면 1이다.
    둘 다 같은 뜻이므로 합으로 나눠 맞춘다 — 사용자가 단위를 신경 쓸
    이유가 없다.

    비중을 아예 안 주면 똑같이 나눈다. '일단 세 개 넣어 보자' 가
    가장 흔한 첫 사용이라, 거기서 막히면 안 된다.
    """
    쓸것 = [a for a in 자산들 if a.get("symbol")][:최대자산]
    if not 쓸것:
        return []
    합 = sum(float(a.get("weight") or 0) for a in 쓸것)
    if 합 <= 0:
        고른비중 = 1.0 / len(쓸것)
        return [{**a, "weight": 고른비중} for a in 쓸것]
    return [{**a, "weight": float(a.get("weight") or 0) / 합} for a in 쓸것]


def 주기날들(날들: list[date], 주기: str, 기준일: int = 1) -> set[date]:
    """그 주기에 해당하는 **거래일**들.

    달의 1일이 휴장이면 그날은 없다. 그래서 날짜를 고정해 찾지 않고
    **기준일이 되거나 지난 첫 거래일**을 고른다. 날짜를 딱 맞춰
    찾으면 휴장 때문에 그 달의 적립이 통째로 빠진다 — 8년이면 몇
    번은 반드시 걸린다.

    기준일 — 달의 며칠에 넣고 싶은가(화면의 '리밸런싱 날짜').
             1이면 달이 바뀌자마자, 15면 중순에 넣는다. 월급날에
             맞춰 적립하는 사람이 많아서 이 선택이 필요하다.
             그 달에 기준일 이후 거래일이 없으면 그 달은 건너뛴다 —
             없는 날을 앞당겨 만들어 내지 않는다.

    첫날은 안 넣는다. 첫날은 초기 투자가 들어가는 날이라,
    같이 넣으면 첫 달만 두 번 납입된다.
    """
    if 주기 == "none" or len(날들) < 2:
        return set()

    기준일 = min(max(int(기준일 or 1), 1), 28)

    def 칸(d: date):
        if 주기 == "monthly":
            return (d.year, d.month)
        if 주기 == "quarterly":
            return (d.year, (d.month - 1) // 3)
        return (d.year,)

    나온것: set[date] = set()
    앞칸 = 칸(날들[0])
    쓴칸: set = {앞칸} if 기준일 > 1 else set()
    for d in 날들[1:]:
        이칸 = 칸(d)
        if 기준일 <= 1:
            if 이칸 != 앞칸:
                나온것.add(d)
                앞칸 = 이칸
            continue
        """기준일이 2 이상이면 '칸이 바뀐 첫날' 이 아니라 '그 칸에서
        기준일을 지난 첫날' 이다. 달마다 한 번만 고르려고 이미 고른
        칸을 따로 적어 둔다 — 안 그러면 15일부터 월말까지 매일
        걸린다(그렇게 짰다가 적립이 열 배로 불어났다)."""
        if 이칸 not in 쓴칸 and d.day >= 기준일:
            나온것.add(d)
            쓴칸.add(이칸)
    return 나온것


def 월말만(날들: list[date]) -> list[date]:
    """달마다 **마지막 거래일**만 남긴다 — 화면의 '월 데이터'.

    1980년부터 돌리면 일별로는 1만 2천 점이다. 그만큼을 브라우저로
    보내 그리면 폰에서 버벅이고, 정작 눈으로 읽는 것은 달 단위 흐름이다.

    긴 기간을 볼 때 월 데이터가 **더 정확한** 것은 아니다. 최대 낙폭은
    달 안에서 난 것을 못 보므로 실제보다 작게 나온다. 그래서 고르게
    두고 기본은 일 데이터로 둔다 — 짧은 기간에 월로 보면 점이 몇 개뿐이라
    아무것도 안 보인다.
    """
    if not 날들:
        return []
    나온것 = []
    for i, d in enumerate(날들):
        끝인가 = i == len(날들) - 1 or (날들[i + 1].year, 날들[i + 1].month) != (d.year, d.month)
        if 끝인가:
            나온것.append(d)
    return 나온것


def _irr(현금흐름: list[tuple[date, float]], 최종: float, 끝날: date) -> Optional[float]:
    """금액가중 연수익률(IRR).

    현금흐름은 (날짜, 넣은 돈) 목록이고 마지막에 최종평가액을 받는 것으로
    친다. 넣은 돈은 음수로, 받는 돈은 양수로 두는 관례를 따른다.

    닫힌 해가 없어서 이분법으로 찾는다. 뉴턴법은 빠르지만 적립식
    현금흐름에서 발산하는 경우가 있어(부호가 여러 번 바뀐다) 쓰지 않는다 —
    느려도 늘 답을 주는 쪽이 낫다. 구간을 -99%~+1000% 로 잡으면
    현실의 어떤 포트폴리오도 그 안에 든다.
    """
    if not 현금흐름 or 최종 <= 0:
        return None
    흐름 = [(d, -금액) for d, 금액 in 현금흐름] + [(끝날, 최종)]
    첫날 = 흐름[0][0]

    def 현재가치(r: float) -> float:
        합 = 0.0
        for d, 금액 in 흐름:
            해 = (d - 첫날).days / 365.25
            합 += 금액 / ((1 + r) ** 해)
        return 합

    낮, 높 = -0.99, 10.0
    f낮, f높 = 현재가치(낮), 현재가치(높)
    if f낮 * f높 > 0:
        return None                       # 구간 안에 답이 없다 — 지어내지 않는다
    for _ in range(200):
        가운데 = (낮 + 높) / 2
        f = 현재가치(가운데)
        if abs(f) < 1e-6:
            break
        if f낮 * f > 0:
            낮, f낮 = 가운데, f
        else:
            높 = 가운데
    return (낮 + 높) / 2


def _mdd(값들: list[float]) -> float:
    """고점 대비 최대 낙폭(%). 양수로 돌려준다."""
    꼭대기 = 값들[0] if 값들 else 0.0
    최대 = 0.0
    for v in 값들:
        if v > 꼭대기:
            꼭대기 = v
        if 꼭대기 > 0:
            낙폭 = (꼭대기 - v) / 꼭대기 * 100
            if 낙폭 > 최대:
                최대 = 낙폭
    return 최대


def _해마다(날들: list[date], 값들: list[float],
            납입: dict[date, float]) -> list[dict]:
    """해마다 얼마나 벌었나.

    **납입을 빼고** 센다. 안 빼면 매달 넣는 사람은 어떤 해든 '플러스' 가
    나온다 — 넣은 돈이 수익으로 둔갑한다. 그해에 넣은 돈을 뺀 나머지가
    실제로 시장에서 난 몫이다.
    """
    if not 날들:
        return []
    해별: dict[int, list[int]] = {}
    for i, d in enumerate(날들):
        해별.setdefault(d.year, []).append(i)

    나온것 = []
    for 해 in sorted(해별):
        칸 = 해별[해]
        """첫해의 시작값은 **0** 이다.

        값들[0] 을 쓰면 안 된다. 그 값은 이미 초기 투자가 들어간 뒤의
        평가액인데, 초기 투자는 아래 그해납입에도 들어 있다 — 같은 돈을
        두 번 세는 셈이라 첫해가 늘 큰 마이너스로 나온다.
        (실제로 그렇게 짰다가 '값이 하나도 안 변했는데 -23.8%' 가
         나오는 것을 검사가 잡았다.)"""
        시작 = 값들[칸[0] - 1] if 칸[0] > 0 else 0.0
        끝 = 값들[칸[-1]]
        그해납입 = sum(금액 for d, 금액 in 납입.items() if d.year == 해)
        밑 = 시작 + 그해납입
        if 밑 <= 0:
            continue
        나온것.append({"year": 해, "return": round((끝 - 밑) / 밑 * 100, 2)})
    return 나온것


def 돌리기(
    가격표: dict[str, dict[date, float]],
    자산들: list[dict],
    초기금액: float,
    적립주기: str = "none",
    적립금액: float = 0.0,
    리밸런싱: str = "none",
    배당: Optional[dict[str, dict[date, float]]] = None,
    거래비용: float = 0.0,
    리밸런싱날: int = 1,
    적립날짜: int = 1,
    현금이자: float = 0.0,
    무위험수익률: float = 0.0,
) -> dict:
    """자산배분을 하루하루 굴려 본다.

    가격표 — {심볼: {날짜: 가격}}. **이미 표시 통화로 바꾼** 값이다.
             환산은 부르는 쪽(라우트)이 한다. 여기서는 환율을 모른다.
    거래비용 — 0.001 이면 0.1%. 살 때도 팔 때도 매긴다.

             리밸런싱은 판 만큼 사는 것이라 **양쪽에 다 붙는다.**
             한쪽만 매기면 비용이 절반으로 나와, 자주 리밸런싱할수록
             유리해 보이는 거꾸로 된 결과가 나온다.

             현금에는 안 매긴다 — 사고파는 것이 아니다.
    리밸런싱날 / 적립날짜 — 달의 며칠에 할까(1~28).
    현금이자 — 연 이율(0.03 이면 3%). **현금도 이자를 받는다.**

             예전에는 늘 0 이었다. 올웨더처럼 현금을 20% 담는 조합을
             30년 돌리면 그 몫이 30년 내내 한 푼도 안 불어난 셈이 되어,
             현금을 담을수록 실제보다 나쁘게 나왔다. 예금이나 MMF 에
             두는 것이 보통이라 0 은 현실이 아니다.

    무위험수익률 — 연 이율(0.03 이면 3%). 샤프를 잴 때 빼는 수.

             샤프는 원래 '무위험으로 그냥 둬도 얻었을 것' 을 뺀 초과
             수익을 위험으로 나눈 값이다. 0 으로 두면 금리가 5% 인 해에
             연 5% 를 번 전략이 초과수익 0 인데도 샤프가 0.5 로 나온다.
             기본값은 0 이지만, **무엇을 가정했는지 응답에 적어 보낸다** —
             가정이 화면에 안 보이는 것이 0 자체보다 나쁘다.
    배당   — {심볼: {날짜: 주당 배당금}}. 주면 그날 재투자한다.

             **이게 이중 계산이 아닌 근거** — yfinance 는 기본값
             (auto_adjust=True)이면 배당이 이미 반영된 조정 종가를 준다.
             그 값에 배당을 또 더하면 배당을 두 번 세는 셈이다.
             이 프로젝트는 yf_service 가 auto_adjust=False 로 **실제
             종가**를 받는다(그 파일 355줄에 왜인지 적혀 있다). 그래서
             여기서 재투자하는 것이 맞다.

             앞으로 그 설정을 바꾸면 이 자리가 조용히 이중 계산이 된다.
             값은 그럴듯하게 나오고 오류도 안 나므로 눈으로는 못 찾는다.

    ── 왜 겹치는 날만 쓰나 ──

    자산마다 상장일이 다르다. 2015년에 생긴 ETF 와 1993년 S&P500 을
    같이 담으면 1993년에는 한쪽 값이 없다. 없는 쪽을 0 으로 치면
    포트폴리오가 갑자기 반토막 난 것처럼 보이고, 마지막 값을 끌어다
    쓰면 상장 전에 이미 갖고 있던 셈이 된다. 둘 다 거짓이다.

    **모든 자산에 값이 있는 날**만 쓴다. 그래서 요청한 기간보다 짧아질
    수 있고, 얼마나 짧아졌는지를 응답에 적는다.
    """
    쓸자산 = 정규화(자산들)
    if not 쓸자산 or 초기금액 <= 0:
        return {}

    시세자산 = [a for a in 쓸자산 if a["symbol"] not in 현금류]
    if 시세자산:
        날집합 = None
        for a in 시세자산:
            가진날 = set(가격표.get(a["symbol"], {}))
            날집합 = 가진날 if 날집합 is None else (날집합 & 가진날)
        날들 = sorted(날집합 or [])
    else:
        # 전부 현금이면 시세가 없다. 굴릴 것이 없으므로 재지 않는다.
        return {}

    if len(날들) < 20:
        return {}

    # ── 첫날: 비중대로 산다 ──
    #
    # 소수점 주식을 허용한다. 실제로는 1주 단위로 사야 하지만, 여기서
    # 반올림하면 비중이 어긋나고 그 오차가 8년 동안 누적된다. 요즘은
    # 소수점 매수를 지원하는 증권사도 많다 — 그쪽이 덜 틀린다.
    비용률 = max(float(거래비용 or 0.0), 0.0)
    비용합 = 0.0
    #: 현금에는 수수료가 안 붙는다. 적립한 돈 중 현금으로 가는 몫만큼은
    #  비용을 빼면 안 되므로 미리 구해 둔다.
    현금비중 = sum(a["weight"] for a in 쓸자산 if a["symbol"] in 현금류)

    첫날 = 날들[0]
    보유: dict[str, float] = {}
    현금몫 = 0.0
    for a in 쓸자산:
        몫 = 초기금액 * a["weight"]
        if a["symbol"] in 현금류:
            현금몫 += 몫
            continue
        """비용만큼 덜 산다.
        수수료를 '나중에 따로 빼는 돈' 으로 두면 안 된다 — 실제로는
        살 때 그만큼 못 사는 것이고, 못 산 몫은 그 뒤 30년을 못 굴린다.
        차이는 복리로 벌어진다."""
        비용 = 몫 * 비용률
        비용합 += 비용
        값 = 가격표[a["symbol"]][첫날]
        보유[a["symbol"]] = (몫 - 비용) / 값 if 값 > 0 else 0.0

    적립날 = 주기날들(날들, 적립주기, 적립날짜) if 적립금액 > 0 else set()
    리밸날 = 주기날들(날들, 리밸런싱, 리밸런싱날)

    곡선: list[dict] = []
    값들: list[float] = []
    납입기록: dict[date, float] = {첫날: 초기금액}
    현금흐름: list[tuple[date, float]] = [(첫날, 초기금액)]
    배당합 = 0.0

    for 칸, d in enumerate(날들):
        # ── 현금 이자 ──
        # 지난 날 수만큼 붙인다. 거래일 사이가 사흘(주말)이면 사흘치다.
        # 날 수로 세야 휴장이 많은 해에도 이자가 안 새어 나간다.
        if 현금이자 > 0 and 현금몫 > 0 and 칸 > 0:
            지난날 = (d - 날들[칸 - 1]).days
            if 지난날 > 0:
                현금몫 *= (1 + 현금이자) ** (지난날 / 365.25)

        # ── 배당 재투자 ──
        # 그날 배당이 있으면 받은 돈으로 같은 종목을 더 산다.
        # 다른 자산으로 옮기지 않는다 — 그건 리밸런싱이 할 일이다.
        if 배당:
            for 심볼, 표 in 배당.items():
                주당 = 표.get(d)
                if not 주당 or 심볼 not in 보유:
                    continue
                받은돈 = 보유[심볼] * 주당
                값 = 가격표[심볼].get(d, 0)
                if 값 > 0 and 받은돈 > 0:
                    보유[심볼] += 받은돈 / 값
                    배당합 += 받은돈

        평가 = 현금몫 + sum(보유[s] * 가격표[s][d] for s in 보유)

        # ── 적립 ──
        if d in 적립날:
            for a in 쓸자산:
                몫 = 적립금액 * a["weight"]
                if a["symbol"] in 현금류:
                    현금몫 += 몫
                    continue
                비용 = 몫 * 비용률
                비용합 += 비용
                값 = 가격표[a["symbol"]][d]
                if 값 > 0:
                    보유[a["symbol"]] += (몫 - 비용) / 값
            평가 += 적립금액 - 적립금액 * 비용률 * (1 - 현금비중)
            납입기록[d] = 납입기록.get(d, 0) + 적립금액
            현금흐름.append((d, 적립금액))

        # ── 리밸런싱 ──
        # 비중이 틀어진 만큼 팔고 사서 목표로 되돌린다.
        # 적립과 같은 날이면 적립을 **먼저** 한다 — 넣은 돈까지 포함해
        # 비중을 맞추는 것이 실제 순서다.
        if d in 리밸날 and 평가 > 0:
            """옮기는 금액에 비용을 매긴다.

            판 쪽과 산 쪽 **양쪽**이다. 100을 팔아 100을 사면 200어치를
            거래한 것이고, 수수료도 200 기준으로 나간다. |목표-현재| 를
            모두 더하면 그 값이 된다(판 합 + 산 합).

            한쪽만 매기면 비용이 절반이라, 자주 리밸런싱할수록 유리해
            보이는 거꾸로 된 결과가 나온다."""
            거래액 = 0.0
            if 비용률 > 0:
                for a in 쓸자산:
                    if a["symbol"] in 현금류:
                        continue          # 현금은 사고파는 것이 아니다
                    지금 = 보유.get(a["symbol"], 0.0) * 가격표[a["symbol"]][d]
                    거래액 += abs(평가 * a["weight"] - 지금)
                비용 = 거래액 * 비용률
                비용합 += 비용
                평가 -= 비용

            현금몫 = 0.0
            for a in 쓸자산:
                몫 = 평가 * a["weight"]
                if a["symbol"] in 현금류:
                    현금몫 += 몫
                    continue
                값 = 가격표[a["symbol"]][d]
                보유[a["symbol"]] = 몫 / 값 if 값 > 0 else 0.0

        곡선.append({"date": d.isoformat(), "value": round(float(평가), 2)})
        값들.append(float(평가))

    총납입 = sum(납입기록.values())
    최종 = 값들[-1]
    해수 = (날들[-1] - 날들[0]).days / 365.25

    """TWR(시간가중) — 납입의 영향을 지운 수익률.

    하루하루의 수익률을 곱해 나간다. 납입이 있던 날은 **넣은 돈을 뺀**
    값으로 비교해야 한다. 안 그러면 돈을 넣은 날이 '하루 만에 +50%' 로
    잡혀서, 많이 넣을수록 성적이 좋아지는 엉터리 수가 된다."""
    누적 = 1.0
    #: 납입을 지운 '내 돈 1원이 어떻게 굴렀나' 곡선. 낙폭도 여기서 잰다.
    순곡선 = [1.0]
    for i in range(1, len(값들)):
        앞 = 값들[i - 1]
        넣은돈 = 납입기록.get(날들[i], 0.0)
        if 앞 <= 0:
            순곡선.append(누적)
            continue
        누적 *= (값들[i] - 넣은돈) / 앞
        순곡선.append(누적)
    twr = (누적 ** (1 / 해수) - 1) * 100 if 해수 >= 1.0 and 누적 > 0 else None

    irr = _irr(현금흐름, 최종, 날들[-1])
    irr_연 = irr * 100 if irr is not None and 해수 >= 1.0 else None

    # 연변동성 — 일간 수익률의 표준편차를 연으로 늘린다
    일간 = []
    for i in range(1, len(값들)):
        앞 = 값들[i - 1]
        넣은돈 = 납입기록.get(날들[i], 0.0)
        if 앞 > 0:
            일간.append((값들[i] - 넣은돈 - 앞) / 앞)
    """연으로 늘릴 때 곱하는 수는 **자료에서 직접 센다.**

    예전에는 늘 √252 였다. 그런데 화면에서 '월별로 재기' 를 고르면
    라우트가 월말만 남겨서 한 칸이 한 달이 된다. 거기에 √252 를 곱하면
    √252/√12 = 4.58배가 부풀려진다 — 실측으로 같은 값·같은 기간인데
    **변동성 17.6% → 82.1%, 샤프 0.77 → 3.54** 였다. 샤프 3.54 는
    세계 최고 헤지펀드 수준의 수라, 사람이 보면 자기 전략이 대단한 줄
    안다. MDD 가 작게 나온다는 경고는 화면에 있는데 이건 없었다.

    12 나 252 를 골라 넣는 대신 **몇 칸이 1년인지를 자료에 물어본다.**
    일별이면 251 근처, 월별이면 12 근처가 나온다. 주별이나 구멍 많은
    자료에서도 알아서 맞고, 라우트가 무엇을 골랐는지 엔진이 몰라도 된다."""
    변동성 = None
    샤프 = None
    if len(일간) > 2 and 해수 > 0:
        연칸수 = len(일간) / 해수
        평균 = sum(일간) / len(일간)
        분산 = sum((x - 평균) ** 2 for x in 일간) / (len(일간) - 1)
        표준 = 분산 ** 0.5
        변동성 = 표준 * (연칸수 ** 0.5) * 100
        if 표준 > 0:
            #: 한 칸당 무위험수익. 연 이율을 칸 수로 쪼갠다.
            #  그냥 나누지 않고 복리로 쪼개야 연으로 되돌렸을 때 맞는다.
            칸무위험 = ((1 + 무위험수익률) ** (1 / 연칸수) - 1) if 연칸수 > 0 else 0.0
            샤프 = (평균 - 칸무위험) / 표준 * (연칸수 ** 0.5)

    def _수(v, 자리=2):
        return None if v is None else round(float(v), 자리)

    return {
        "start_date": 날들[0].isoformat(),
        "end_date": 날들[-1].isoformat(),
        "years": round(해수, 2),
        "contributed": _수(총납입),
        "final_value": _수(최종),
        "profit": _수(최종 - 총납입),
        #: 내 돈 대비 얼마나 불었나. 적립식에서는 이 수가 유일하게
        #  '내가 번 돈' 을 정직하게 말한다.
        "total_return": _수((최종 - 총납입) / 총납입 * 100) if 총납입 > 0 else None,
        #: 전략끼리 비교할 때 쓰는 수(납입 시점의 영향을 지운 것)
        "twr_annual": _수(twr),
        #: 내가 실제로 번 연 수익률(늦게 넣은 돈은 덜 굴었다는 것이 반영)
        "irr_annual": _수(irr_연),
        #: 낙폭은 **납입을 지운 곡선**에서 잰다.
        #
        #  평가액 곡선으로 재면 적립식에서 낙폭이 작게 나온다. 매달 넣는
        #  돈이 곡선을 밀어 올려 하락을 가리기 때문이다 — 똑같이 -40% 를
        #  맞은 자료로 재 보니 거치식 37.7% 인데 적립식은 32.8% 였다.
        #  '내 돈이 얼마나 줄었나' 를 묻는 수인데 새로 넣은 돈이 그 답을
        #  좋게 만든 셈이다.
        #
        #  거치식(납입이 한 번뿐)에서는 두 곡선이 같아 값이 안 바뀐다.
        "mdd": _수(_mdd(순곡선)),
        "volatility": _수(변동성),
        "sharpe": _수(샤프, 3),
        #: 샤프를 잴 때 무엇을 무위험으로 봤나(연 %). 화면에 적어야 한다 —
        #  가정을 감춘 수는 사람이 자기 기준으로 읽어 버린다.
        "risk_free_rate": round(무위험수익률 * 100, 2),
        #: 현금에 붙인 연 이율(%). 0 이면 '현금은 안 불어난다' 는 뜻이고,
        #  그것도 하나의 가정이므로 숨기지 않는다.
        "cash_rate": round(현금이자 * 100, 2),
        "dividends": _수(배당합) if 배당 else None,
        #: 낸 수수료 합. 0%로 돌렸으면 0 이 아니라 None 이다 —
        #  '안 넣었다' 와 '넣었는데 0원' 은 다른 말이다.
        "costs": _수(비용합) if 비용률 > 0 else None,
        "cost_rate": 비용률 if 비용률 > 0 else None,
        "yearly": _해마다(날들, 값들, 납입기록),
        "curve": 곡선,
    }
