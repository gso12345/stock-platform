def _야후심볼(symbol: str, market: str) -> str:
    """국내 종목은 야후에서 접미사가 필요하다."""
    s = (symbol or "").upper()
    if market != "KR":
        return s
    if s.endswith(".KS") or s.endswith(".KQ"):
        return s
    return f"{s}.KS" if s.isdigit() else s


def _주기(날들: list) -> "str | None":
    """지난 기준일 간격으로 배당 주기를 읽는다.

    간격의 '가운데 값' 을 쓴다. 평균을 쓰면 특별배당 한 번이 통째로
    주기를 흔든다 — 삼성전자처럼 분기배당에 결산배당이 겹치는 종목이
    실제로 그렇다."""
    if len(날들) < 2:
        return None
    간격 = sorted((날들[i] - 날들[i - 1]).days for i in range(1, len(날들)))
    if not 간격:
        return None
    가운데 = 간격[len(간격) // 2]
    if 가운데 <= 10:
        # 주배당 ETF(APLY·NVDY·AMZY 같은 것). '월' 로 묶으면 한 달에
        # 네 번 받는 것을 한 번으로 세어 예상액이 4분의 1이 된다
        return "주"
    if 가운데 <= 45:
        return "월"
    if 가운데 <= 135:
        return "분기"
    if 가운데 <= 270:
        return "반기"
    if 가운데 <= 500:
        return "연"
    return None


_주기일수 = {"주": 7, "월": 30, "분기": 91, "반기": 182, "연": 365}

#: 한 달에 몇 번 받나. 주배당은 4~5주라 평균을 쓴다(365/12/7)
_한달회차 = {"주": 4.35, "월": 1.0, "분기": 1.0, "반기": 1.0, "연": 1.0}


def _월별일정(최근: list, 날들: list, 주기: "str | None") -> list:
    """달마다 '며칠에, 주당 얼마' 를 실제 내역에서 뽑는다.

    ── 왜 필요한가 ──

    지금까지 화면은 마지막 회차 금액(last_amount) 하나를 열두 달에 다
    썼다. 그런데 분기배당은 회차마다 금액이 다르다 — 결산배당이 붙는
    4분기가 특히 크다. 마지막 회차가 그 큰 회차면 한 해 예상이 통째로
    부풀고, 작은 회차면 반대로 깎인다.

    예: 분기마다 0.20 / 0.25 / 0.30 / 0.35 를 주는 종목이면 한 해 1.10
    인데, 마지막 회차(0.35)를 네 번 곱하면 1.40 이 된다 — 27% 를 더
    받는 것으로 나온다.

    ── 어떻게 뽑나 ──

    달마다 **가장 최근 해의 실제 지급액**을 쓴다. 주배당·월배당처럼 한
    달에 여러 번 주는 종목은 그 달 안의 지급을 합친다.

    날짜는 그 달에 실제로 준 날이다. '분기배당은 91일마다' 로 미루면
    회차마다 며칠씩 밀려서 1년 뒤에는 달이 바뀐다 — 3월 말에 주던
    종목이 4월로 넘어가 버린다.
    """
    if not 최근:
        return []
    자를날 = date.today() - timedelta(days=365 * 되짚는_해)
    칸: dict = {}
    for x, d in zip(최근, 날들):
        if d < 자를날:
            continue
        칸.setdefault(d.month, []).append((d, float(x.get("amount") or 0)))

    올해 = date.today().year
    결과 = []
    for m in sorted(칸):
        것들 = sorted(칸[m])
        """어느 해 것을 쓰나 — **올해가 있으면 올해**.

        예전에는 '것들[-1] 의 해' 였다. 바로 위에서 정렬하므로 결과는
        같다 — 이 줄은 동작을 바꾸지 않는다. 규칙을 눈에 보이게 적을
        뿐이다. 그래도 적어 두는 이유는, 바로 아래 `올해확정` 이 이
        규칙 위에 서 있어서다. 정렬을 지우거나 자료를 다른 데서 받아
        오는 날 그 플래그가 조용히 뒤집히면, 화면이 작년 값에 '올해
        확정' 을 붙인다.

        여기서 한 가지가 분명해진다 — 한 종목의 열두 칸은 **서로 다른
        해에서 나온다**. 오늘이 8월이면 1~8월 칸은 올해 실제 지급이고
        9~12월 칸만 작년 것이다. 그런데 화면은 그 열두 칸에 죄다
        '작년 기준' 을 붙이고 있었다 — 열두 달 중 여덟 달이 틀린 말이다.
        고친 것은 그쪽이다."""
        최신해 = 올해 if any(d.year == 올해 for d, _ in 것들) else 것들[-1][0].year

        """두 해 넘게 안 준 달은 칸을 아예 안 만든다.

        창이 730일이라 재작년 지급도 후보에 남는다. 그래서 작년에 12월
        배당을 없애고 11월로 옮긴 종목이면, 12월 막대가 재작년 금액으로
        계속 서 있고 그 금액이 '연간 배당금' 에 더해진다 — 한 해 예상이
        한 회차만큼 부풀어 나온다."""
        if 최신해 < 올해 - 1:
            continue

        같은해 = [(d, a) for d, a in 것들 if d.year == 최신해]
        결과.append({
            "month": m,
            "day": 같은해[-1][0].day,
            "amount": round(sum(a for _, a in 같은해), 6),
            "year": 최신해,
            #: 올해 실제로 받은 달인가. 화면이 '올해 확정' 과 '작년 기준' 을
            #: 가려 적는 데 쓴다 — 예전에는 화면이 연도를 안 보고 모든 칸에
            #: '작년 기준' 을 붙여서, 올해 3월에 받은 값 위에도 그 말이 찍혔다.
            "올해확정": 최신해 == 올해,
            #: 그 달에 **날짜별로** 얼마씩 받았나.
            #
            #  주배당(연 52회)은 한 달에 네다섯 번 준다. 그걸 한 칸으로
            #  접으면 화면에 '8월 20일 · 주당 $0.189' 한 줄만 남는데,
            #  날짜는 그 달 **마지막** 지급일이고 금액은 그 달 **합계**라
            #  둘의 기준이 서로 다르다. 나란히 찍으면 그냥 틀린 줄이다.
            #
            #  재료는 이미 여기 다 있다. 접기 전에 그대로 실어 보낸다.
            "days": [{"date": d.isoformat(), "amount": round(a, 6)}
                     for d, a in 같은해],
            #: 이 칸이 실제 지급 내역에서 나온 것인가.
            #
            #  아래 주·월배당 메우기가 없는 달을 평균으로 채우는데,
            #  그건 실제로 받은 값이 아니다. 화면이 둘을 구분해 말할 수
            #  있어야 한다 — 지어낸 값을 실제인 척 보여 주면, 그 숫자로
            #  한 해 계획을 세우는 사람이 생긴다.
            "actual": True,
        })
    return 결과


def _해달별합(최근: list, 날들: list) -> list:
    """해·달마다 실제로 얼마를 받았나 — 지난 내역을 압축한 것.

    화면은 '그 달에 해마다 얼마였나' 를 두 줄만 적는다. 그걸 위해
    지난 지급 내역(recent)을 통째로 실어 보내고 있었는데, 주배당이면
    한 종목에 104건이다. 열두 종목이면 그 배열만 51KB — **응답의 절반**
    이고, 화면은 그중 두 줄을 쓴다.

    여기서 미리 묶어 보내면 최대 24줄(2년 × 12달)이다. 주배당에서
    104건 → 24건이고, 화면이 하던 합산도 사라진다.
    """
    칸: dict = {}
    for x, d in zip(최근, 날들):
        칸[(d.year, d.month)] = 칸.get((d.year, d.month), 0.0) + float(x.get("amount") or 0)
    return [{"year": y, "month": m, "amount": round(a, 6)}
            for (y, m), a in sorted(칸.items(), reverse=True)]


def _다음_일정(일정: list, 오늘: "date | None" = None) -> "date | None":
    """월별 일정에서 앞으로 제일 가까운 날.

    예전에는 '마지막 기준일 + 주기일수' 였다. 91일씩 더하면 회차마다
    며칠씩 밀리고, 네 번 밀리면 364일이라 한 해에 하루씩 앞당겨진다 —
    몇 해 지나면 달이 바뀐다. 실제로 준 달·날을 그대로 쓴다."""
    if not 일정:
        return None
    오늘 = 오늘 or date.today()
    후보 = []
    for 해 in (오늘.year, 오늘.year + 1):
        for 칸 in 일정:
            try:
                d = date(해, 칸["month"], min(칸["day"], _그달끝(해, 칸["month"])))
            except ValueError:
                continue
            if d >= 오늘:
                후보.append(d)
    return min(후보) if 후보 else None


def _그달끝(해: int, 달: int) -> int:
    """그 달의 마지막 날. 2월 30일 같은 날짜를 만들지 않으려고."""
    import calendar as _cal
    return _cal.monthrange(해, 달)[1]


def _다음_예상(마지막: date, 주기: "str | None") -> "date | None":
    """마지막 기준일 + 주기. 이미 지난 날짜가 나오면 올 때까지 민다.

    한 번만 더하면 오래 안 들여다본 종목에서 과거 날짜가 나온다 —
    달력에 지난 날짜가 '다음 배당' 으로 찍히는 것은 그냥 틀린 정보다."""
    일수 = _주기일수.get(주기 or "")
    if not 일수:
        return None
    다음 = 마지막 + timedelta(days=일수)
    오늘 = date.today()
    돈수 = 0
    while 다음 < 오늘 and 돈수 < 24:
        다음 += timedelta(days=일수)
        돈수 += 1
    return 다음 if 다음 >= 오늘 else None


def _가져오기(symbol: str, market: str) -> dict:
    """야후에서 한 종목의 배당을 읽는다. 실패하면 빈 dict."""
    import yfinance as yf

    야후 = _야후심볼(symbol, market)
    t = yf.Ticker(야후)

    최근: list[dict] = []
    try:
        s = t.dividends
        if s is not None and len(s):
            for 날, 금액 in list(s.items())[-최근_건수:]:
                try:
                    d = 날.date() if hasattr(날, "date") else 날
                    최근.append({"date": d.isoformat(), "amount": float(금액)})
                except Exception:
                    continue
    except Exception as e:
        log.debug("배당 내역 실패 %s: %s", 야후, type(e).__name__)

    if not 최근:
        return {}                      # 배당을 안 주는 종목이거나 못 받았다

    날들 = [date.fromisoformat(x["date"]) for x in 최근]
    주기 = _주기(날들)

    """지난 1년치 합 = 연 배당금.

    '주당 얼마' 는 종목마다 자릿수가 달라(삼성전자 361원, 애플 0.25달러)
    그 자체로는 비교가 안 된다. 화면에서 수량을 곱해 '내가 받을 돈' 으로
    쓰려고 여기서 합만 내 둔다."""
    한해전 = date.today() - timedelta(days=365)
    연배당 = round(sum(x["amount"] for x, d in zip(최근, 날들) if d >= 한해전), 6)

    """배당월 — 이 종목이 몇 월에 주나.

    화면이 '2, 5, 8, 11' 처럼 적어 준다. 분기배당이라도 회사마다 달이
    달라서(2·5·8·11 vs 3·6·9·12), 이걸 안 적으면 한 해 계획을 못 세운다.

    주배당·월배당은 열두 달 전부다."""
    일정 = _월별일정(최근, 날들, 주기)
    if 주기 in ("주", "월"):
        배당월 = list(range(1, 13))
        # 아직 한 해가 안 찬 종목은 빈 달이 생긴다. 월배당인 걸 아는데
        # 몇 달이 비어 보이면 '그 달은 안 준다' 로 읽힌다 — 있는 달들의
        # 평균으로 메운다
        있는것 = {x["month"]: x for x in 일정}
        if 있는것:
            평균 = round(sum(x["amount"] for x in 있는것.values()) / len(있는것), 6)
            어느날 = sorted(있는것.values(), key=lambda x: x["month"])[-1]["day"]
            # 메운 칸은 actual=False 다. 실제로 받은 값이 아니라 있는
            # 달들의 평균이라, 화면이 '평균' 이라고 밝힐 수 있어야 한다
            일정 = [있는것.get(m) or {"month": m, "day": 어느날, "amount": 평균,
                                      "year": None, "actual": False}
                    for m in 배당월]
    else:
        배당월 = [x["month"] for x in 일정]
        if not 배당월:
            배당월 = sorted({d.month for d in 날들})

    확정일 = 지급일 = None
    확정일_원본 = 지급일_원본 = None
    try:
        cal = t.calendar or {}
        ex = cal.get("Ex-Dividend Date")
        pay = cal.get("Dividend Date")
        """공시된 날짜는 지났어도 버리지 않는다.

        예전에는 `>= 오늘` 로 걸러 과거면 값 **자체를** 없앴다. 야후는
        직전(이미 지난) 기준일을 담는 일이 잦아서 거의 항상 이 컷에
        걸렸고, 그러면 회사가 공시한 확정 일정이 손에 있는데도 화면은
        '예상 · 9월 중순' 으로 떨어졌다.

        지금은 원값을 그대로 담고, '앞으로의 것인가' 만 따로 표시한다.
        **기준일은 지났는데 지급일은 아직인** 흔한 상태에서, 화면이
        '지급 예정 9월 26일 (확정)' 이라고 정확히 말할 수 있게 된다."""
        오늘 = date.today()
        if isinstance(ex, date):
            확정일_원본 = ex.isoformat()
            if ex >= 오늘:
                확정일 = 확정일_원본
        if isinstance(pay, date):
            지급일_원본 = pay.isoformat()
            if pay >= 오늘:
                지급일 = 지급일_원본
    except Exception as e:
        log.debug("배당 일정 실패 %s: %s", 야후, type(e).__name__)

    예상일 = None
    if not 확정일:
        """주·월배당은 주기로 밀고, 나머지는 달·날 패턴을 쓴다.

        여기가 어긋나 있었다. 월별 일정 칸에는 그 달에 **마지막으로 준
        날** 하나만 들어 있다. 주배당(7일마다)에 그걸 쓰면, 이번 달
        지급이 끝난 뒤부터는 다음 달 마지막 주까지 통째로 건너뛴다 —
        매주 받는 사람에게 '다음 배당은 한 달 뒤' 라고 말하는 셈이다.
        실제로 재 봤다: 8월 27일에 물으면 9월 25일이 나왔다.

        분기·연배당은 반대다. 주기로 밀면(91일씩) 회차마다 며칠씩
        밀려 몇 해 뒤에는 달이 바뀐다 — 3월 말에 주던 종목이 4월로
        넘어간다. 그쪽은 실제로 준 달·날을 그대로 써야 한다."""
        if 주기 in ("주", "월"):
            d = _다음_예상(날들[-1], 주기) or _다음_일정(일정)
        else:
            d = _다음_일정(일정) or _다음_예상(날들[-1], 주기)
        예상일 = d.isoformat() if d else None

    """앞으로 받을 날들 — 주·월배당만.

    분기·연배당은 다음 회차 하나만 알면 된다(estimated_date). 그런데
    주배당은 '언제 받나' 가 곧 '매주 무슨 요일' 이라, 날짜 하나로는
    그 종목의 모양을 못 보여 준다.

    지어낸 값이라는 것을 감추지 않는다 — 지난 지급(schedule[].days)과
    **다른 배열**로 내보내서, 화면이 둘을 섞을 수 없게 한다."""
    앞으로 = []
    if 주기 in ("주", "월") and 날들:
        일수 = _주기일수[주기]
        걸음 = 날들[-1]
        오늘 = date.today()
        최근금액 = round(float(최근[-1]["amount"] or 0), 6)
        while len(앞으로) < 앞으로_최대:
            걸음 = 걸음 + timedelta(days=일수)
            if 걸음 < 오늘:
                continue
            if (걸음 - 오늘).days > 앞으로_며칠:
                break
            앞으로.append({"date": 걸음.isoformat(), "amount": 최근금액})

    return {
        "symbol": symbol, "market": market,
        "recent": 최근,
        #: 해·달마다 실제로 받은 합계. 화면이 '그 달에 해마다 얼마였나'
        #: 를 적는 데 쓴다 — recent 를 통째로 보낼 이유가 없다
        "월별지난": _해달별합(최근, 날들),
        "per_year": 연배당,
        #: 앞으로 한 해 받을 것으로 보이는 주당 금액.
        #
        #  per_year(지난 1년 실제 합)와 다를 수 있다 — 반년 전에 배당을
        #  시작한 종목은 지난 1년 합이 반년치뿐이라 실제보다 작게 나온다.
        #  화면이 '한 해 예상' 으로 쓰는 것은 이쪽이다.
        "plan_year": round(sum(x["amount"] for x in 일정), 6) if 일정 else 연배당,
        #: 달마다 며칠에 주당 얼마 — [{"month":3,"day":31,"amount":0.25}, ...]
        "schedule": 일정,
        "cycle": 주기,
        #: 몇 월에 주나 — [2, 5, 8, 11]. 주·월배당은 1~12 전부
        "months": 배당월,
        #: 한 달에 몇 번. 주배당만 1보다 크다
        "per_month": _한달회차.get(주기 or "", 1.0),
        #: 국내면 원, 아니면 달러. 화면이 원화로 환산할 때 쓴다
        "currency": "KRW" if market == "KR" else "USD",
        "last_date": 최근[-1]["date"],
        "last_amount": 최근[-1]["amount"],
        # 회사가 공시한 날짜 중 **앞으로의 것**. 있으면 이쪽이 옳다
        "ex_date": 확정일,
        "pay_date": 지급일,
        #: 공시된 날짜 원본 — 지난 것도 담는다.
        #
        #  '기준일은 지났고 지급일만 남았다' 는 흔한 상태를 화면이
        #  말할 수 있어야 한다. 위 두 칸은 미래만 담으므로 그때 비어 있다.
        "ex_date_공시": 확정일_원본,
        "pay_date_공시": 지급일_원본,
        # 없을 때만 쓰는 추정치. 화면에서 '예상' 이라고 밝힌다
        "estimated_date": 예상일,
        #: 앞으로 받을 날들 — 주·월배당만. **전부 추정이다.**
        #  지난 지급(schedule[].days)과 다른 배열에 두어 섞이지 않게 한다
        "upcoming": 앞으로,
    }


def 한종목(symbol: str, market: str, 받아도되나: bool = True) -> dict:
    """담긴 것 → 지난 것 → (여유가 있으면) 직접. 없으면 빈 dict."""
    ck = f"div:{market}:{symbol}"
    if (c := cache.get(ck)) is not None:
        return c
    if (s := cache.get_stale(ck)) is not None:
        return s
    if not 받아도되나 or 쉼.쉬는가(ck):
        return {}

    def 받기():
        try:
            결과 = _가져오기(symbol, market)
        except Exception as e:
            log.debug("배당 조회 실패 %s: %s", symbol, type(e).__name__)
            쉼.기록(ck, True)
            return {}
        쉼.기록(ck, not 결과)
        if 결과:
            cache.set(ck, 결과, 수명)
        return 결과

    return 캐시_우선(ck, 받기, {}, miss_ttl=빈손수명)


def 달력(보유: list) -> dict:
    """내 종목들의 배당을 날짜순으로 묶는다.

    `보유` 는 (symbol, market, name, shares) 를 가진 것들. shares 가
    0 이면 관심종목처럼 '갖고 있진 않지만 보고 싶은' 것으로 친다.

    한 요청에 새로 받는 종목 수를 묶는다. 처음 몇 번은 목록이 조금씩
    길어지는 대신, 화면이 30초를 기다리는 일이 없다."""
    줄들 = []
    못받음 = 0

    # 쉬는 종목을 뒤로 미룬다 — 살아 있는 것부터 칸을 쓴다
    열쇠 = lambda x: f"div:{x.get('market')}:{x.get('symbol')}"      # noqa: E731
    차례 = 쉼.돌아가며_깨우기(list(보유 or []), 열쇠)
    """미룬 것을 문자열 열쇠로 가른다.

    `x not in 차례` 로 dict 를 통째로 비교하고 있었다. 항목마다 차례
    전체를 훑으므로 종목 수의 제곱이다. 게다가 값이 같은 dict 가 둘이면
    (지금은 라우트가 (symbol, market) 로 중복을 없애 주지만, 부르는 쪽이
    바뀌면) 중복이 통째로 빠진다."""
    깨운것 = {열쇠(x) for x in 차례}
    미룬것 = [x for x in (보유 or []) if 열쇠(x) not in 깨운것]
    순서 = 차례 + 미룬것

    """새로 받을 종목을 먼저 골라 **한꺼번에** 받는다.

    아래 반복문은 종목마다 한종목() 을 부르는데, 캐시에 없으면 그 자리에서
    바깥에 물어본다. 차례로 부르면 열두 종목이 왕복 열두 번이고, 그게
    그대로 화면 대기다. 실제로 재 봤다 — 아홉 종목에 **2,242ms**.

    받는 일은 바깥을 기다리는 일(I/O)이라, 스레드로 겹쳐 두면 제일 느린
    하나만큼만 걸린다. 0.15 CPU 서버에서도 손해가 없다 — CPU 를 쓰는
    일이 아니라 답을 기다리는 일이라서다.

    상한(남은칸)은 여기서 정한다. 아래 반복문은 이 결정을 그대로 따르고,
    받아 둔 것을 캐시에서 꺼내 쓴다."""
    받을것 = []
    남길칸 = 한번에
    for it in 순서:
        sym, mkt = it.get("symbol"), it.get("market")
        if not sym or not mkt:
            continue
        ck = f"div:{mkt}:{sym}"
        if cache.get(ck) is not None or cache.get_stale(ck) is not None:
            continue                     # 이미 있다
        if 빈손인가(ck) or 쉼.쉬는가(ck):
            continue                     # 답이 이미 나왔거나 쉬는 중
        if 남길칸 <= 0:
            break
        남길칸 -= 1
        받을것.append((sym, mkt))

    if 받을것:
        # 한 번에 여섯까지. 더 늘려도 바깥이 막으면 소용이 없고,
        # 스레드가 늘수록 메모리도 같이 는다(무료 서버는 512MB 다)
        일꾼 = min(len(받을것), 6)
        """여기서 터지는 것은 **다 삼킨다.**

        스레드 안에서 난 예외는 result() 에서 다시 튀어나온다. 지금은
        한종목() 이 안에서 삼키므로 대개 안 오지만, 그건 다른 모듈의
        사정이다 — 캐시가 터지거나 한종목() 이 예외를 그대로 올리도록
        바뀌면 이 자리가 그대로 500 이 된다. 배당 하나 때문에 내 자산
        화면 전체가 죽는 것은 너무 큰 대가다.

        받아 둔 것이 없으면 아래 반복문이 pending 으로 정직하게 세어
        내보내고, 화면이 몇 초 뒤 다시 물어본다.

        (result() 마다 따로 감싸 봤는데 뮤테이션으로 지워도 아무 검사가
         안 깨졌다 — 이 바깥 가드가 이미 다 잡고 있어서다. 같은 일을
         두 겹으로 하지 않는다.)"""
        try:
            with _ThreadPool(max_workers=일꾼) as 풀:
                맡김 = [풀.submit(한종목, s, m, True) for s, m in 받을것]
                for 일 in 맡김:
                    일.result()
        except Exception as e:
            log.debug("배당 미리받기 건너뜀: %s", type(e).__name__)

    for it in 순서:
        sym, mkt = it.get("symbol"), it.get("market")
        if not sym or not mkt:
            continue
        ck = f"div:{mkt}:{sym}"
        담긴것 = cache.get(ck) or cache.get_stale(ck)
        """배당을 **안 주는** 종목은 칸을 안 쓴다.

        여기가 조용히 망가져 있었다. 무배당 종목(성장주가 대부분이다)은
        값 캐시(ck)에 아무것도 안 담긴다 — 대신 fetchcache 가 다른 열쇠
        `ck:miss` 에 '빈손' 표시를 사흘 남긴다. 그래서 담긴것이 영원히
        None 이고, 매 요청마다 남은칸을 하나씩 깎았다.

        정작 한종목() 은 그 표시를 보고 곧바로 빈손을 돌려주므로 목록에는
        한 줄도 안 보탠다. **칸만 태우고 아무것도 안 채우는 것**이다.

        그 결과 무배당 종목이 몇 개만 섞여 있어도 pending 이 0 이 안 되고,
        화면은 '아직 덜 받았다' 로 읽어 영원히 다시 물어본다. 배당을 주는
        종목이 다 채워졌는데도 그렇다.

        빈손인 것은 칸도 안 쓰고 못받음에도 안 센다 — 이미 답이 나온
        종목이지, 아직 못 받은 종목이 아니다."""
        빈손 = 담긴것 is None and 빈손인가(ck)
        """여기서는 **안 받는다.** 받는 일은 위에서 이미 끝났다.

        예전에는 이 자리에서 남은칸을 깎아 가며 직접 받았다. 미리받기를
        붙이면서 그 셈이 두 번이 됐다 — 위에서 열둘을 받아 캐시에 넣으면
        여기서는 그 열둘이 '이미 있는 것' 이라 칸을 안 쓰고, 남은 것들에
        열두 칸을 **다시** 내준다. 검사로 잡았다: 상한이 12인데 17번을
        받았다.

        상한은 한 곳에서만 센다. 여기 남은 것은 다음 요청 몫이라
        못받음(pending)으로 넘긴다 — 화면이 그 수를 보고 몇 초 뒤에
        한 번 더 물어본다."""
        정보 = 한종목(sym, mkt, 받아도되나=False)
        if not 정보:
            if not 빈손:
                # 빈손은 '아직 못 받은 것' 이 아니라 '답이 나온 것' 이다
                못받음 += 1
            continue

        날 = 정보.get("ex_date") or 정보.get("estimated_date")
        if not 날:
            continue
        수량 = float(it.get("shares") or 0)
        """이번 회차 주당 금액 — 그 달에 **실제로 준** 금액을 쓴다.

        마지막 회차 금액(last_amount)을 쓰고 있었다. 분기배당은 회차마다
        금액이 다르므로(결산배당이 붙는 분기가 특히 크다) 그 값은 다음
        회차와 아무 상관이 없다. 0.20/0.25/0.30/0.35 를 주는 종목이
        다음에 0.20 을 줄 차례인데 마지막이 0.35 였으면, 화면은 75% 를
        더 받는다고 말한다."""
        그달 = int(날.split("-")[1])
        칸 = next((x for x in (정보.get("schedule") or []) if x.get("month") == 그달), None)
        회차주당 = float((칸 or {}).get("amount") or 정보.get("last_amount") or 0)
        """달력 응답에서는 지난 내역 원본(recent)을 뺀다.

        화면은 '그 달에 해마다 얼마였나' 만 적는데, 그건 위에서 묶어 둔
        월별지난으로 충분하다. 원본은 주배당이면 한 종목에 104건이라
        열두 종목 응답의 **절반**을 차지했다 — 받아서 버리는 몫이다.

        종목 상세의 공개 경로(/stocks/{market}/{symbol}/dividends)에는
        그대로 남긴다. 거기는 한 종목뿐이라 값이 싸고, 앞으로 원본이
        필요한 화면이 생길 수 있다."""
        가벼운것 = {k: v for k, v in 정보.items() if k != "recent"}
        줄들.append({
            **가벼운것,
            "name": it.get("name") or sym,
            "shares": 수량,
            "date": 날,
            "confirmed": bool(정보.get("ex_date")),
            #: 이번 회차 주당 금액. 화면이 같은 값을 다시 안 찾아도 되게 싣는다
            "next_amount": round(회차주당, 6),
            # 이번 회차에 받을 것으로 보이는 돈. 수량이 0이면 안 낸다
            "expected": round(수량 * 회차주당, 2) if 수량 else None,
            # 한 해에 받을 것으로 보이는 돈. 지난 1년 실제 합(per_year)이
            # 아니라 앞으로 한 해 계획(plan_year)을 쓴다 — 화면의 월별
            # 막대를 다 더한 값과 같아야 두 숫자가 서로 안 어긋난다
            "expected_year": round(수량 * float(정보.get("plan_year") or 정보.get("per_year") or 0), 2) if 수량 else None,
        })

    줄들.sort(key=lambda x: x["date"])
    return {"items": 줄들, "pending": 못받음}


