/** 주관사 칸 → 증권사 이름들 — 사용자: "공모주 일정 증권사별로 설정해서 볼수 있게 만들어줘" */
import { describe, it, expect } from "vitest";
import { 증권사들, 증권사별수, 내증권사공모주, 알림증권사칩, 자주주관하는증권사 } from "../ipoBrokers";

describe("증권사들", () => {
  it("여럿이면 나눈다 — 쉼표·빗금·가운뎃점, 앞뒤 빈칸", () => {
    expect(증권사들("미래에셋증권,KB증권")).toEqual(["미래에셋증권", "KB증권"]);
    expect(증권사들("한국투자증권, 삼성증권 / NH투자증권·키움증권")).toEqual(
      ["한국투자증권", "삼성증권", "NH투자증권", "키움증권"]);
  });

  it("괄호·㈜ 와 '외 N' 은 뺀다", () => {
    expect(증권사들("NH투자증권(대표), 삼성증권(공동)")).toEqual(["NH투자증권", "삼성증권"]);
    expect(증권사들("㈜키움증권")).toEqual(["키움증권"]);
    expect(증권사들("KB증권 외 2")).toEqual(["KB증권"]);
    expect(증권사들("대신증권외3개사")).toEqual(["대신증권"]);
  });

  it("옛 이름은 지금 이름으로 — 같은 증권사가 둘로 갈리지 않게", () => {
    expect(증권사들("신한금융투자")).toEqual(["신한투자증권"]);
    expect(증권사들("하나증권,하나금융투자")).toEqual(["하나증권"]);
    expect(증권사들("미래에셋대우")).toEqual(["미래에셋증권"]);
  });

  it("없거나 '-' 면 빈 목록", () => {
    expect(증권사들(null)).toEqual([]);
    expect(증권사들(undefined)).toEqual([]);
    expect(증권사들("")).toEqual([]);
    expect(증권사들("-")).toEqual([]);
  });
});

describe("증권사별수", () => {
  it("증권사마다 주관하는 곳 수 — 많은 순, 같으면 이름 순", () => {
    expect(증권사별수(["미래에셋증권,KB증권", "KB증권", null, "대신증권", "KB증권,대신증권", "미래에셋증권"]))
      .toEqual([["KB증권", 3], ["대신증권", 2], ["미래에셋증권", 2]]);
  });
});

describe("내증권사공모주", () => {
  it("아무것도 안 골랐으면 모두, 골랐으면 그중 하나라도 주관하는 것만", () => {
    expect(내증권사공모주(null, [])).toBe(true);
    expect(내증권사공모주("미래에셋증권,KB증권", ["KB증권"])).toBe(true);
    expect(내증권사공모주("미래에셋증권", ["KB증권", "삼성증권"])).toBe(false);
    expect(내증권사공모주(null, ["KB증권"])).toBe(false);
    expect(내증권사공모주("신한금융투자", ["신한투자증권"])).toBe(true);
  });
});

// 알림 설정에서 고르는 칩 — "알림설정에서 그냥 어떤 증권사만 알림이 오게할지 설정할 수 있도록 해줘"
describe("알림증권사칩", () => {
  it("서버 목록 뒤에, 거기 없는데 골라 둔 증권사를 붙인다 — 같은 이름은 한 번", () => {
    expect(알림증권사칩(["KB증권", "삼성증권"], ["삼성증권", "상상인증권"])).toEqual(["KB증권", "삼성증권", "상상인증권"]);
  });

  it("서버 목록이 없거나 비면 자주 주관하는 곳", () => {
    for (const 없음 of [undefined, null, []]) {
      expect(알림증권사칩(없음, [])).toEqual(자주주관하는증권사);
    }
    expect(알림증권사칩([], ["상상인증권"])).toEqual([...자주주관하는증권사, "상상인증권"]);
  });

  it("자주 주관하는 곳은 지금 이름이고 겹치지 않는다 — 옛 이름이면 공모주 기록과 안 맞는다", () => {
    expect(new Set(자주주관하는증권사).size).toBe(자주주관하는증권사.length);
    for (const 이름 of 자주주관하는증권사) expect(증권사들(이름)).toEqual([이름]);
    expect(자주주관하는증권사.length).toBeGreaterThanOrEqual(15);
  });
});
