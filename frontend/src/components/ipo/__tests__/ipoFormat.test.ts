import { describe, it, expect } from "vitest";
import { 날짜글, 남은날, 숫자로, 경쟁률글, 억원글, 배율퍼센트, 퍼센트글 } from "../ipoFormat";

const 오늘 = new Date("2026-10-09T03:00:00Z");   // 한국 2026-10-09 낮

describe("공모주 글자", () => {
  it("올해 날짜는 월.일, 지난해 것은 해를 붙인다 — 지난해 10.16 이 '아직 안 온 날' 로 읽히지 않게", () => {
    expect(날짜글("2026-10-13", 오늘)).toBe("10.13");
    expect(날짜글("2025-10-16", 오늘)).toBe("25.10.16");
    expect(날짜글(null, 오늘)).toBe("—");
  });

  it("한국 날짜로 며칠 남았는지 센다", () => {
    expect(남은날("2026-10-12", 오늘)).toBe(3);
    expect(남은날("2026-10-09", 오늘)).toBe(0);
    expect(남은날("2026-10-08", 오늘)).toBe(-1);
    // 한국은 이미 10일 새벽(UTC 9일 16시)
    expect(남은날("2026-10-10", new Date("2026-10-09T16:00:00Z"))).toBe(0);
  });

  it("쉼표·단위를 넣어 적어도 읽는다", () => {
    expect(숫자로("15,000")).toBe(15000);
    expect(숫자로("1,234.5:1")).toBe(1234.5);
    expect(숫자로("40%")).toBe(40);
    expect(숫자로("12,000원")).toBe(12000);
    expect(숫자로("  ")).toBeNull();
    expect(숫자로("abc")).toBeNaN();
  });

  it("경쟁률·공모금액·배율", () => {
    expect(경쟁률글(1234.56)).toBe("1,235:1");
    expect(경쟁률글(3.25)).toBe("3.3:1");
    expect(억원글(18000)).toBe("180억");
    expect(억원글(50)).toBe("50백만");
    expect(배율퍼센트(1.544)).toBe(54);
    expect(퍼센트글(-12)).toBe("-12%");
    expect(퍼센트글(0)).toBe("0%");
  });
});
