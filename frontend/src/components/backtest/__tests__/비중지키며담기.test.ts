/**
 * 자산을 더해도 **이미 맞춰 둔 비중을 날리지 않는가.**
 *
 * ── 무엇이 문제였나 ────────────────────────────────────────
 *
 * 담을 때마다 전부 똑같이 나눴다. 빈 화면에서 하나씩 담을 때는 맞는
 * 동작이지만, 비중을 이미 정해 둔 뒤에는 그것을 통째로 날린다 —
 *
 *     내 포트폴리오를 비중 그대로(75/25) 담아 놓고
 *     금을 하나 더하면 → 33.3 / 33.3 / 33.3
 *
 * 가져온 비중이 그 기능의 본론인데 자산 하나 더했다고 사라진다.
 * 손으로 60/40 을 맞춰 둔 사람도 마찬가지다. 오류도 안 나고, 비중
 * 칸을 다시 보지 않으면 그대로 돌려 버린다 — 조용히 다른 포트폴리오를
 * 재게 되는, 이 기능에서 제일 나쁜 실패다.
 */
import { describe, it, expect } from "vitest";

import { 자산더하기 } from "../AllocationForm";
import type { 배분자산 } from "@/api/stocks";

const 자산 = (symbol: string, weight: number): 배분자산 =>
  ({ symbol, market: "US", name: symbol, weight });

const 몫 = (xs: 배분자산[]) =>
  Object.fromEntries(xs.map((x) => [x.symbol, x.weight]));
const 합 = (xs: 배분자산[]) => xs.reduce((a, x) => a + x.weight, 0);


describe("있던 비중을 **손대지 않는다**", () => {
  it("75/25 에 하나 더해도 75/25 그대로다", () => {
    /* 비율만 지키고 수를 바꾸는 방식(50/16.7)도 써 봤다. 비율은
       지켜지지만 **적어 둔 수가 바뀐다** — 75 라고 쳐 둔 칸이 50 이
       되어 있으면 내가 뭘 잘못 눌렀나 싶어 다시 세어 보게 된다. */
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("C", 0));
    const w = 몫(r);
    expect(w.A, "가져온 비중이 바뀌었다").toBe(75);
    expect(w.B).toBe(25);
  });

  it("새로 담은 것은 0% 로 들어온다", () => {
    /* 얼마를 줄지는 사람이 정한다 — 그게 이 화면에서 하려는 일이다. */
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("C", 0));
    expect(몫(r).C).toBe(0);
  });

  it("합이 그대로 100 이다", () => {
    //: 75 + 25 + 0 = 100. 노란 '합 99.9%' 가 뜰 일이 없다.
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("C", 0));
    expect(합(r)).toBe(100);
  });

  it("여러 번 더해도 처음 수가 그대로다", () => {
    let xs = [자산("A", 80), 자산("B", 20)];
    for (const s of ["C", "D", "E"]) xs = 자산더하기(xs, 자산(s, 0));
    const w = 몫(xs);
    expect(w.A).toBe(80);
    expect(w.B).toBe(20);
    expect([w.C, w.D, w.E]).toEqual([0, 0, 0]);
    expect(합(xs)).toBe(100);
  });

  it("하나만 담겨 있어도 안 건드린다", () => {
    const r = 자산더하기([자산("A", 100)], 자산("B", 0));
    expect(몫(r)).toEqual({ A: 100, B: 0 });
  });
});


describe("빈 화면에서 하나씩 담는 예전 동작은 그대로", () => {
  it("아무것도 없으면 100%", () => {
    expect(몫(자산더하기([], 자산("A", 0))).A).toBe(100);
  });

  it("비중이 다 0 이면 똑같이 나눈다", () => {
    /* 나눌 비율이 없다. 이때까지 비율을 지키려 들면 0 으로 나눈다. */
    const r = 자산더하기([자산("A", 0), 자산("B", 0)], 자산("C", 0));
    for (const v of Object.values(몫(r))) expect(v).toBeCloseTo(33.3, 1);
  });

  it("비중을 안 준 동안에는 계속 균등하게 들어온다", () => {
    /* 빈 화면에서 하나씩 담는 흐름이다. 여기서까지 0% 로 넣으면
       첫 자산부터 합이 0 이 되어 아무것도 못 돌린다. */
    let xs = 자산더하기([], 자산("A", 0));
    expect(몫(xs).A).toBe(100);
    xs = 자산더하기(xs, 자산("B", 0));
    //: A 에 100 이 붙었으므로 이제 '비중이 있는' 상태 — B 는 0% 다
    expect(몫(xs)).toEqual({ A: 100, B: 0 });
  });

  it("이미 똑같이 나뉘어 있으면 새것은 0% 다", () => {
    /* 50/50 도 '사람이 정해 둔 비중' 이다. 33.3 셋으로 바꾸면 그
       사람이 맞춰 둔 반반이 사라진다. 균등하게 만들고 싶으면
       '동일비중' 단추가 따로 있다. */
    const r = 자산더하기([자산("A", 50), 자산("B", 50)], 자산("C", 0));
    expect(몫(r)).toEqual({ A: 50, B: 50, C: 0 });
  });
});


describe("같은 종목은 두 번 안 담는다", () => {
  it("이미 있으면 그대로 돌려준다", () => {
    const 있던것 = [자산("A", 75), 자산("B", 25)];
    const r = 자산더하기(있던것, 자산("A", 0));
    expect(r).toBe(있던것);
  });

  it("막을 때 비중도 안 건드린다", () => {
    /* 막으면서 비중만 다시 나누면, 아무 일도 안 일어난 줄 아는데
       숫자는 바뀌어 있다. */
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("B", 0));
    expect(몫(r)).toEqual({ A: 75, B: 25 });
  });
});
