/**
 * 자산을 더해도 **이미 맞춰 둔 비중을 날리지 않는가.**
 *
 * ── 무엇이 문제였나 ────────────────────────────────────────
 *
 * 담을 때마다 전부 똑같이 나눴다. 빈 화면에서 하나씩 담을 때는 맞는
 * 동작이지만, 비중을 이미 정해 둔 뒤에는 그것을 통째로 날린다 —
 *
 *     내 포트폴리오를 비중 그대로(75/25) 담아 놓고
 *     금을 하나 더하면 → 33.3 / 33.3 / 33.3
 *
 * 가져온 비중이 그 기능의 본론인데 자산 하나 더했다고 사라진다.
 * 손으로 60/40 을 맞춰 둔 사람도 마찬가지다. 오류도 안 나고, 비중
 * 칸을 다시 보지 않으면 그대로 돌려 버린다 — 조용히 다른 포트폴리오를
 * 재게 되는, 이 기능에서 제일 나쁜 실패다.
 */
import { describe, it, expect } from "vitest";

import { 자산더하기 } from "../AllocationForm";
import type { 배분자산 } from "@/api/stocks";

const 자산 = (symbol: string, weight: number): 배분자산 =>
  ({ symbol, market: "US", name: symbol, weight });

const 몫 = (xs: 배분자산[]) =>
  Object.fromEntries(xs.map((x) => [x.symbol, x.weight]));
const 합 = (xs: 배분자산[]) => xs.reduce((a, x) => a + x.weight, 0);


describe("있던 비중의 **비율**을 지킨다", () => {
  it("75/25 에 하나 더해도 3:1 이 그대로다", () => {
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("C", 0));
    const w = 몫(r);
    expect(w.A / w.B, "가져온 비중이 날아갔다").toBeCloseTo(3, 1);
  });

  it("새로 담은 것은 똑같이 나눈 몫(1/n)을 갖는다", () => {
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("C", 0));
    expect(몫(r).C).toBeCloseTo(33.3, 1);
  });

  it("0% 로 들여보내지 않는다", () => {
    /* '담았는데 결과에 아무 영향이 없는' 상태는 고장으로 읽힌다. */
    const r = 자산더하기([자산("A", 100)], 자산("B", 0));
    expect(몫(r).B).toBeGreaterThan(0);
  });

  it("여러 번 더해도 처음 비율이 남는다", () => {
    /* 한 번만 보면 반올림에 가려 안 보이는 어긋남이, 서너 번 쌓이면
       드러난다. */
    let xs = [자산("A", 80), 자산("B", 20)];
    for (const s of ["C", "D", "E"]) xs = 자산더하기(xs, 자산(s, 0));
    const w = 몫(xs);
    expect(w.A / w.B, "여러 번 담으니 비율이 무너졌다").toBeCloseTo(4, 1);
  });
});


describe("합이 100 이 된다", () => {
  it("한 번 담아도 100", () => {
    /* 99.9 가 되면 화면에 '합 99.9%' 가 노란 글씨로 떠서, 사용자가
       뭘 잘못했나 찾게 만든다. */
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("C", 0));
    expect(합(r)).toBeCloseTo(100, 5);
  });

  it("세 번 담아도 100", () => {
    let xs = [자산("A", 70), 자산("B", 30)];
    for (const s of ["C", "D", "E"]) {
      xs = 자산더하기(xs, 자산(s, 0));
      expect(합(xs), `${s} 를 담고 나서 합이 100 이 아니다`).toBeCloseTo(100, 5);
    }
  });

  it("셋으로 나눠지지 않는 수에서도 100", () => {
    //: 33.3 × 3 = 99.9 — 부스러기를 어딘가에 몰아 줘야 한다
    const r = 자산더하기([자산("A", 50), 자산("B", 50)], 자산("C", 0));
    expect(합(r)).toBeCloseTo(100, 5);
  });
});


describe("빈 화면에서 하나씩 담는 예전 동작은 그대로", () => {
  it("아무것도 없으면 100%", () => {
    expect(몫(자산더하기([], 자산("A", 0))).A).toBe(100);
  });

  it("비중이 다 0 이면 똑같이 나눈다", () => {
    /* 나눌 비율이 없다. 이때까지 비율을 지키려 들면 0 으로 나눈다. */
    const r = 자산더하기([자산("A", 0), 자산("B", 0)], 자산("C", 0));
    for (const v of Object.values(몫(r))) expect(v).toBeCloseTo(33.3, 1);
  });

  it("이미 똑같이 나뉘어 있으면 계속 똑같이 나뉜다", () => {
    /* 50/50 에 더하면 셋이 거의 똑같아진다 — 예전과 같은 결과다.
       비율을 지키는 규칙이 이 경우를 저절로 포함한다.

       **딱 33.3 셋은 아니다.** 33.3 × 3 = 99.9 라 부스러기 0.1 을
       하나가 받는다(33.4/33.3/33.3, 합 100). 예전에는 그 부스러기를
       버려서 합이 99.9 였고, 화면에 노란 글씨로 '합 99.9%' 가 떴다. */
    const 값들 = Object.values(몫(자산더하기(
      [자산("A", 50), 자산("B", 50)], 자산("C", 0))));
    //: 부동소수점이라 0.1 이 0.10000000000000142 로 나온다 — 반올림해서 본다
    expect(Math.round((Math.max(...값들) - Math.min(...값들)) * 10) / 10,
      "똑같이 나뉘어야 하는데 차이가 부스러기보다 크다").toBeLessThanOrEqual(0.1);
    expect(값들.reduce((a, b) => a + b, 0)).toBeCloseTo(100, 5);
  });
});


describe("같은 종목은 두 번 안 담는다", () => {
  it("이미 있으면 그대로 돌려준다", () => {
    const 있던것 = [자산("A", 75), 자산("B", 25)];
    const r = 자산더하기(있던것, 자산("A", 0));
    expect(r).toBe(있던것);
  });

  it("막을 때 비중도 안 건드린다", () => {
    /* 막으면서 비중만 다시 나누면, 아무 일도 안 일어난 줄 아는데
       숫자는 바뀌어 있다. */
    const r = 자산더하기([자산("A", 75), 자산("B", 25)], 자산("B", 0));
    expect(몫(r)).toEqual({ A: 75, B: 25 });
  });
});
