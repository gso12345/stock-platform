/**
 * 이 종목이 ETF 인가.
 *
 * 예전에는 이름에 "ETF" 라는 글자가 들어가는지만 봤다. 그런데 국내 ETF 이름은
 * 그렇게 짓지 않는다 — KODEX 200, TIGER 미국나스닥100, RISE 200, ACE 국고채10년.
 * 어디에도 "ETF" 가 없다. 그래서 사실상 모든 국내 ETF 가 일반 종목으로 취급됐다.
 *
 * 그 결과가 이랬다.
 *   - '보유비중' 탭이 안 나온다 (ETF 에서만 나오게 돼 있다)
 *   - 대신 '재무제표'·'투자의견' 탭이 나오는데, ETF 에는 그런 게 없어서 텅 빈다
 *   - '수급' 탭까지 나온다 (일반 국내 종목으로 보므로)
 *   - 배지가 'KOSPI' 로 뜬다
 *
 * 국내 ETF 는 이름이 반드시 운용사 브랜드로 시작한다. 브랜드는 몇 개 안 되고
 * 잘 바뀌지 않으므로(바뀌면 예전 이름도 한동안 함께 쓰인다) 이것이 가장 튼튼한
 * 단서다. 종목 코드 범위로 가르는 방법도 있지만 예외가 많다.
 *
 * 백엔드가 종목 종류를 내려주게 되면 이 파일은 그 값을 그대로 쓰면 된다.
 */

/** 국내 ETF·ETN 운용사 브랜드. 이름 맨 앞에 온다.
 *
 *  이름이 바뀐 것들은 옛 이름도 남겨 둔다 — 상장된 종목명이 한꺼번에
 *  바뀌지 않고, 캐시에 옛 이름이 남아 있을 수도 있다.
 *    KBSTAR → RISE (KB, 2024)
 *    ARIRANG → PLUS (한화, 2024)
 *    KINDEX → ACE (한국투자, 2022) */
const 브랜드 = [
  "KODEX", "TIGER", "RISE", "KBSTAR", "PLUS", "ARIRANG", "ACE", "KINDEX",
  "HANARO", "KOSEF", "SOL", "TIMEFOLIO", "WOORI", "히어로즈", "BNK",
  "마이다스", "파워", "FOCUS", "KTOP", "TREX", "마이티", "네비게이터",
  "에셋플러스", "UNICORN", "다banking", "삼성", "미래에셋", "한국투자",
  "신한", "키움", "메리츠", "NH", "하나", "대신", "IBK", "교보",
] as const;

/* 브랜드 이름만으로는 부족한 경우가 있다 — '삼성전자' 는 브랜드 '삼성' 으로
   시작하지만 ETF 가 아니다. 그래서 브랜드 뒤에 공백이 오는 것만 인정하고,
   일반 종목으로 오인되기 쉬운 브랜드는 ETF 임을 알리는 낱말을 함께 요구한다. */
const 애매한브랜드 = new Set([
  "삼성", "미래에셋", "한국투자", "신한", "키움", "메리츠", "NH", "하나",
  "대신", "IBK", "교보", "파워", "우리", "WOORI",
]);

/** ETF·ETN 임을 드러내는 낱말 */
const 낱말 = /(ETF|ETN|인버스|레버리지|선물|합성|TR\b|액티브|커버드콜|채권|국고채|배당주|리츠|\d+배)/i;

/**
 * 이름과 시장으로 ETF 여부를 판단한다.
 *
 * @param market 라우트의 시장 코드. "ETF" 면 두말할 것 없이 ETF 다
 * @param name   종목명. 아직 안 왔으면 빈 문자열
 */
export function isETFStock(market: string, name: string | null | undefined): boolean {
  if ((market || "").toUpperCase() === "ETF") return true;

  const 이름 = (name ?? "").trim();
  /* 지워도 결과는 같다 — 빈 문자열은 아래 두 검사를 어차피 다 통과 못 한다.
     읽는 사람에게 "이름이 없으면 판단하지 않는다" 를 먼저 보이려고 둔다.
     (뮤테이션 테스트에서 이 줄만 안 잡히는데, 없앨 수 없는 종류다) */
  if (!이름) return false;

  // 이름에 대놓고 적혀 있으면 그대로 인정한다 (해외 ETF 가 이렇다)
  if (/\b(ETF|ETN)\b/i.test(이름)) return true;

  const 앞 = 브랜드.find((b) => 이름.toUpperCase().startsWith(b.toUpperCase() + " "));
  if (!앞) return false;

  // '삼성전자' 같은 오인을 막는다 — 위에서 브랜드 뒤 공백을 이미 요구했지만,
  // '삼성 우선주' 처럼 띄어 쓴 일반 종목이 있을 수 있어 한 겹 더 본다
  if (애매한브랜드.has(앞)) return 낱말.test(이름);

  return true;
}
