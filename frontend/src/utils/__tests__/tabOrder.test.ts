/**
 * 관심종목 탭 순서 — "관심종목 폴더관리에서 폴더 뿐만 아니라 최근조회,
 * 폴더, 내계좌도 순서변경이 가능하도록해줘"
 *
 * 탭 줄에는 성격이 다른 셋이 섞여 있다. 예전에는 "최근조회 → 폴더 전부 →
 * 내계좌 전부" 로 굳어 있었고, 옮길 수 있는 것은 폴더끼리뿐이었다.
 *
 * 저장된 순서는 언제나 낡아 있다고 봐야 한다 — 폴더를 지웠을 수도, 계좌를
 * 새로 만들었을 수도, 다른 기기에서 폴더 순서를 바꿨을 수도 있다. 여기서
 * 못 박는 것은 그 낡음을 어떻게 다루느냐다.
 */
import { describe, it, expect, beforeEach } from "vitest";
import {
  최근조회키, 폴더키, 계좌키,
  탭순서읽기, 탭순서쓰기, 탭순서적용, 폴더순서반영,
} from "../tabOrder";

const 탭 = (key: string) => ({ key });

beforeEach(() => localStorage.clear());

describe("저장", () => {
  it("쓴 것을 그대로 읽는다", () => {
    탭순서쓰기(7, ["a", "b"]);
    expect(탭순서읽기(7)).toEqual(["a", "b"]);
  });

  it("사용자마다 따로 남는다", () => {
    /* 같은 브라우저를 둘이 쓰면 남의 순서가 내 화면에 뜬다 */
    탭순서쓰기(7, ["a"]);
    탭순서쓰기(8, ["b"]);
    expect(탭순서읽기(7)).toEqual(["a"]);
    expect(탭순서읽기(8)).toEqual(["b"]);
  });

  it("저장된 것이 없으면 빈 목록", () => {
    expect(탭순서읽기(7)).toEqual([]);
  });

  it("값이 깨져 있어도 터지지 않는다", () => {
    /* 여기서 던지면 순서 하나 때문에 관심종목 화면이 통째로 안 뜬다 */
    localStorage.setItem("watchlistTabOrder:7", "{망가진");
    expect(탭순서읽기(7)).toEqual([]);
    localStorage.setItem("watchlistTabOrder:7", '{"a":1}');
    expect(탭순서읽기(7)).toEqual([]);
    localStorage.setItem("watchlistTabOrder:7", '["a", 3, null]');
    expect(탭순서읽기(7)).toEqual(["a"]);
  });
});

describe("저장된 순서 입히기", () => {
  it("저장된 대로 세운다", () => {
    const 결과 = 탭순서적용(
      [계좌키(1), 최근조회키, 폴더키(3)],
      [탭(최근조회키), 탭(폴더키(3)), 탭(계좌키(1))],
    );
    expect(결과.map((t) => t.key)).toEqual([계좌키(1), 최근조회키, 폴더키(3)]);
  });

  it("사라진 것은 빼고 세운다", () => {
    /* 폴더를 지웠는데 저장된 순서에 남아 있으면, 없는 탭을 그리려다 깨진다 */
    const 결과 = 탭순서적용(
      [폴더키(9), 최근조회키],
      [탭(최근조회키)],
    );
    expect(결과.map((t) => t.key)).toEqual([최근조회키]);
  });

  it("처음 보는 것은 원래 순서대로 뒤에 붙인다", () => {
    /* 앞에 끼우면 방금 만든 폴더가 애써 맞춰 둔 순서를 밀어내고
       맨 앞을 차지한다 */
    const 결과 = 탭순서적용(
      [계좌키(1)],
      [탭(최근조회키), 탭(폴더키(3)), 탭(계좌키(1)), 탭(폴더키(4))],
    );
    expect(결과.map((t) => t.key)).toEqual([계좌키(1), 최근조회키, 폴더키(3), 폴더키(4)]);
  });

  it("저장된 것이 없으면 원래 순서 그대로", () => {
    const 실제 = [탭(최근조회키), 탭(폴더키(3))];
    expect(탭순서적용([], 실제).map((t) => t.key)).toEqual([최근조회키, 폴더키(3)]);
  });

  it("항목을 잃지도 늘리지도 않는다", () => {
    /* 하나라도 흘리면 그 탭은 화면에서 통째로 사라진다 */
    const 실제 = [탭(최근조회키), 탭(폴더키(3)), 탭(폴더키(4)), 탭(계좌키(1))];
    const 결과 = 탭순서적용([폴더키(4), "folder:99", 계좌키(1)], 실제);
    expect(결과).toHaveLength(4);
    expect(new Set(결과.map((t) => t.key))).toEqual(new Set(실제.map((t) => t.key)));
  });
});

describe("폴더끼리만 바꿨을 때", () => {
  it("폴더가 있던 자리에 새 순서를 채운다", () => {
    /* 자리까지 옮기면 폴더 사이에 끼워 둔 내계좌가 딸려 나간다 */
    const 결과 = 폴더순서반영(
      [폴더키(1), 계좌키(9), 폴더키(2), 최근조회키, 폴더키(3)],
      [3, 1, 2],
    );
    expect(결과).toEqual([폴더키(3), 계좌키(9), 폴더키(1), 최근조회키, 폴더키(2)]);
  });

  it("폴더가 아닌 것은 건드리지 않는다", () => {
    const 원본 = [최근조회키, 계좌키(9)];
    expect(폴더순서반영(원본, [1, 2])).toEqual(원본);
  });

  it("저장된 자리보다 폴더가 많아도 있는 자리까지만 채운다", () => {
    /* 다른 기기에서 폴더를 새로 만들었을 때다. 남는 폴더는 탭순서적용이
       뒤에 붙여 준다 */
    expect(폴더순서반영([폴더키(1)], [5, 6, 7])).toEqual([폴더키(5)]);
  });
});

describe("키", () => {
  it("종류가 달라도 안 겹친다", () => {
    /* 폴더 3번과 내계좌 3번이 같은 키가 되면 한쪽이 사라진다 */
    expect(폴더키(3)).not.toBe(계좌키(3));
    expect(new Set([최근조회키, 폴더키(3), 계좌키(3)]).size).toBe(3);
  });
});
