/**
 * 대화 화면의 시각·줄 묶기 — 메신저 앱처럼 보이는가.
 *
 * 시각은 그 기기의 시간대로 읽는다. 검사도 같은 시간대에서 만든 날짜(new Date(년, 월, 일, …))로 본다.
 */
import { describe, it, expect } from "vitest";
import {
  말풍선시각, 날짜줄, 목록시각, 대화줄들, 메시지합치기, 바뀐것있나, type 표시메시지,
} from "@/utils/대화시각";

const 때 = (월: number, 일: number, 시 = 12, 분 = 0, 년 = 2026) => new Date(년, 월 - 1, 일, 시, 분).toISOString();

function 메(id: number, mine: boolean, 시각: string, 덧: Partial<표시메시지> = {}): 표시메시지 {
  return { id, mine, body: `${id}번`, deleted: false, blinded: false, created_at: 시각, ...덧 };
}

describe("말풍선 시각 — '오후 3:12'", () => {
  it.each([
    [0, 5, "오전 12:05"],
    [9, 7, "오전 9:07"],
    [11, 59, "오전 11:59"],
    [12, 0, "오후 12:00"],
    [13, 30, "오후 1:30"],
    [23, 59, "오후 11:59"],
  ])("%i시 %i분 → %s", (시, 분, 글) => {
    expect(말풍선시각(때(11, 6, 시, 분))).toBe(글);
  });

  it("없거나 읽을 수 없으면 빈 글", () => {
    expect(말풍선시각(null)).toBe("");
    expect(말풍선시각(undefined)).toBe("");
    expect(말풍선시각("2026-13-45")).toBe("");
  });
});

describe("날짜 줄", () => {
  it("년·월·일·요일", () => {
    expect(날짜줄(때(11, 6))).toBe("2026년 11월 6일 금요일");
    expect(날짜줄(때(11, 1))).toBe("2026년 11월 1일 일요일");
    expect(날짜줄(때(1, 1, 0, 0, 2027))).toBe("2027년 1월 1일 금요일");
  });
  it("읽을 수 없으면 빈 글", () => {
    expect(날짜줄("없음")).toBe("");
  });
});

describe("목록 시각 — 오늘은 시각, 어제는 '어제', 올해는 월·일, 그 전은 년까지", () => {
  const 지금 = new Date(2026, 10, 6, 15, 0);
  it("오늘", () => expect(목록시각(때(11, 6, 9, 3), 지금)).toBe("오전 9:03"));
  it("어제(밤 늦게도)", () => {
    expect(목록시각(때(11, 5, 23, 59), 지금)).toBe("어제");
    expect(목록시각(때(11, 5, 0, 0), 지금)).toBe("어제");
  });
  it("그제부터는 날짜", () => expect(목록시각(때(11, 4, 23, 59), 지금)).toBe("11월 4일"));
  it("올해", () => expect(목록시각(때(1, 1, 0, 0), 지금)).toBe("1월 1일"));
  it("지난해", () => expect(목록시각(때(12, 31, 12, 0, 2025), 지금)).toBe("2025. 12. 31."));
  it("달·해가 바뀌는 어제", () => {
    expect(목록시각(때(10, 31, 20, 0), new Date(2026, 10, 1, 8, 0))).toBe("어제");
    expect(목록시각(때(12, 31, 20, 0, 2025), new Date(2026, 0, 1, 8, 0))).toBe("어제");
  });
  it("없으면 빈 글", () => expect(목록시각(null, 지금)).toBe(""));
});

describe("줄 묶기", () => {
  it("날이 바뀌면 날짜 줄이 먼저 온다", () => {
    const 줄 = 대화줄들([메(1, false, 때(11, 5, 23, 50)), 메(2, true, 때(11, 6, 0, 10)), 메(3, true, 때(11, 6, 0, 11))], 0);
    expect(줄.map((x) => (x.종류 === "날짜" ? x.글 : x.m.id))).toEqual([
      "2026년 11월 5일 목요일", 1, "2026년 11월 6일 금요일", 2, 3,
    ]);
  });

  it("같은 사람이 같은 분에 보낸 것은 한 묶음 — 시각은 끝에만, 아바타는 처음에만", () => {
    const 줄 = 대화줄들([
      메(1, false, 때(11, 6, 15, 12)),
      메(2, false, 때(11, 6, 15, 12)),
      메(3, false, 때(11, 6, 15, 13)),     // 분이 바뀌면 새 묶음
      메(4, true, 때(11, 6, 15, 13)),      // 사람이 바뀌면 새 묶음
      메(5, true, 때(11, 6, 15, 13)),
    ], 0).filter((x) => x.종류 === "메시지");
    expect(줄.map((x) => x.종류 === "메시지" && [x.m.id, x.묶음첫, x.묶음끝])).toEqual([
      [1, true, false], [2, false, true], [3, true, true], [4, true, false], [5, false, true],
    ]);
  });

  it("'읽음' 은 상대가 읽은 내 메시지 중 마지막 하나에만", () => {
    const 목록 = [
      메(1, true, 때(11, 6, 15, 0)), 메(2, true, 때(11, 6, 15, 1)), 메(3, false, 때(11, 6, 15, 2)),
      메(4, true, 때(11, 6, 15, 3)),
    ];
    const 읽음표 = (상대읽음: number) => 대화줄들(목록, 상대읽음)
      .flatMap((x) => (x.종류 === "메시지" && x.읽음 ? [x.m.id] : []));
    expect(읽음표(0)).toEqual([]);
    expect(읽음표(1)).toEqual([1]);
    expect(읽음표(3)).toEqual([2]);          // 3 은 상대 것 — 내 것 중 마지막(2)에
    expect(읽음표(4)).toEqual([4]);
    expect(읽음표(99)).toEqual([4]);
  });

  it("보내는 중·못 보낸 것(번호 없음)에는 '읽음' 이 붙지 않는다", () => {
    const 줄 = 대화줄들([메(1, true, 때(11, 6)), 메(-1, true, 때(11, 6), { 상태: "보내는중", 임시: "t-1" })], 10);
    const 읽음 = 줄.flatMap((x) => (x.종류 === "메시지" && x.읽음 ? [x.m.id] : []));
    expect(읽음).toEqual([1]);
    expect(줄[줄.length - 1]).toMatchObject({ key: "t-1" });
  });

  it("시각이 없는 메시지도 그린다(날짜 줄만 빠진다)", () => {
    const 줄 = 대화줄들([메(1, true, ""), 메(2, true, 때(11, 6))], 0);
    expect(줄.map((x) => x.종류)).toEqual(["메시지", "날짜", "메시지"]);
  });
});

describe("합치기", () => {
  it("같은 번호는 새 것으로, 번호 차례로, 보내는 중인 것은 끝에", () => {
    const 지금 = [메(5, false, 때(11, 6)), 메(3, true, 때(11, 6)), 메(-1, true, 때(11, 6), { 상태: "보내는중", 임시: "t-1" })];
    const 합 = 메시지합치기(지금, [메(4, false, 때(11, 6)), 메(5, false, 때(11, 6), { deleted: true, body: null })]);
    expect(합.map((m) => m.id)).toEqual([3, 4, 5, -1]);
    expect(합.find((m) => m.id === 5)).toMatchObject({ deleted: true, body: null });
  });

  it("바뀐 것이 있나 — 새 번호·지움·가림·글", () => {
    const 지금 = [메(1, false, 때(11, 6)), 메(2, true, 때(11, 6))];
    expect(바뀐것있나(지금, [])).toBe(false);
    expect(바뀐것있나(지금, [메(1, false, 때(11, 6))])).toBe(false);
    expect(바뀐것있나(지금, [메(3, false, 때(11, 6))])).toBe(true);
    expect(바뀐것있나(지금, [메(1, false, 때(11, 6), { deleted: true })])).toBe(true);
    expect(바뀐것있나(지금, [메(1, false, 때(11, 6), { blinded: true })])).toBe(true);
    expect(바뀐것있나(지금, [메(2, true, 때(11, 6), { body: "고침" })])).toBe(true);
    // 보내는 중인 것(음수)과 같은 번호로 비교하지 않는다
    expect(바뀐것있나([메(-1, true, 때(11, 6), { 임시: "t-1" })], [메(-1, true, 때(11, 6))])).toBe(true);
  });
});
