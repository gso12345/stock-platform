/**
 * 비어 있는 동안만 다시 물어보기.
 *
 * ── 왜 필요한가 ──
 *
 * 서버가 무거운 목록(해외 순위·뉴스)을 만들 때 쓰는 방식이 있다 —
 * 이번 요청은 **있는 것으로 답하고**, 만드는 일은 배경으로 넘긴다.
 * 0.15 CPU 서버에서 화면을 30초씩 붙잡지 않으려는 것이라 옳은 선택이다.
 *
 * 그런데 그러면 화면이 **다시 와서 받아 가야** 한다. 안 그러면 처음 연
 * 사람은 빈 화면을 본다. 실제로 그랬다 —
 *
 *   해외 순위 : staleTime 60초, 재촉 없음   → "아직 순위가 만들어지지 않았어요"
 *   해외 뉴스 : refetchInterval 5분         → "표시할 뉴스가 없어요"
 *
 * 배경 작업은 대개 몇 초면 끝나는데 화면은 1분·5분을 기다렸다. 배당
 * 달력과 보유 뉴스는 이미 pending 을 보고 몇 초 간격으로 다시 묻는다.
 * 같은 규칙을 순위·뉴스에도 쓴다.
 *
 * ── 끝이 있어야 한다 ──
 *
 * 영영 안 채워지는 경우가 있다(원천이 죽었거나, 그 시장이 쉬는 날).
 * 그때 몇 초마다 영원히 두드리면 서버를 제일 세게 때리는 짓이면서
 * 값이 생기지도 않는다. 몇 번만 재촉하고 평소 주기로 물러난다.
 */
import type { Query } from "@tanstack/react-query";

/** 기본 재촉 간격 — 내 자산 화면과 같은 값을 쓴다(constants/portfolioQuery) */
export const 기본재촉 = 4_000;

/** 몇 번까지 재촉할지. 이 뒤로는 평소 주기로 물러난다 */
export const 기본재촉_횟수 = 5;

/**
 * "비어 있으면 재촉, 채워지면 평소대로" 를 돌려준다.
 *
 * react-query 의 refetchInterval 에 그대로 넣는다.
 *
 * @param 평소주기 채워진 뒤의 간격. false 면 그때는 아예 안 묻는다.
 * @param 비었나  무엇을 '비었다' 로 볼지. 안 주면 빈 배열을 뜻한다.
 */
export function 빌때재촉<T>(
  평소주기: number | false,
  비었나: (값: T | undefined) => boolean = (값) =>
    !값 || (Array.isArray(값) && 값.length === 0),
  재촉주기: number = 기본재촉,
  재촉횟수: number = 기본재촉_횟수,
) {
  return (q: Query<T, Error, T>): number | false => {
    if (!비었나(q.state.data)) return 평소주기;
    /* 몇 번만 재촉한다.
       dataUpdateCount 는 '값이 도착한 횟수' 다. 빈 배열도 값이라
       한 번 셀 때마다 늘어난다 — 그래서 이 수로 끊을 수 있다. */
    return q.state.dataUpdateCount <= 재촉횟수 ? 재촉주기 : 평소주기;
  };
}
