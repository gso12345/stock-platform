/**
 * 내 자산 화면이 서버에 물어보는 주기 — 한자리에 모은다.
 *
 * 화면 하나가 여섯 경로를 부르는데, 그 주기가 파일마다 제각각이었다.
 *
 *   시세     staleTime 120초 · 재촉 3초
 *   배당     staleTime 600초 · 재촉 4초
 *   뉴스     staleTime 300초 · 재촉 5초
 *   보유목록 staleTime 300초
 *   자산흐름 staleTime 300초
 *
 * 3·4·5초는 고른 값이 아니라 각자 따로 정한 값이다. 그래서 배당 탭과
 * 뉴스 탭이 같은 '아직 받는 중' 상태인데 다른 속도로 깜빡였고, 하나를
 * 고치려면 세 파일을 찾아야 했다.
 *
 * 성격이 다른 것만 갈라 둔다 —
 *
 *   시세는 **자주 변한다**. 2분이면 낡는다.
 *   배당·뉴스·기록은 하루 단위로 변한다. 5분을 굳혀도 안 낡는다.
 *
 * 배당의 10분을 5분으로 줄인다. 10분은 '전체 포트폴리오 배당 합계가
 * 안 맞는다' 는 제보의 절반이었다 — 서버가 나머지를 채워 놨는데
 * 화면이 10분 동안 안 물어봤다.
 */

/** 자주 변하는 것 — 시세 */
export const 시세수명 = 120_000;

/** 하루 단위로 변하는 것 — 배당·뉴스·보유 목록·자산 흐름 */
export const 하루수명 = 300_000;

/**
 * 서버가 "아직 받는 중"(pending > 0)이라고 할 때 다시 물어보는 간격.
 *
 * 서버는 한 요청에 몇 개까지만 새로 받고 나머지는 배경으로 넘긴다.
 * 이 재촉이 없으면 처음 연 사람은 절반만 보고 나간다.
 *
 * 3초는 짧고 5초는 길다. 0.15 CPU 서버에서 여러 탭이 동시에 재촉하면
 * 그 자체가 부담이라 4초로 맞췄다.
 */
export const 재촉주기 = 4_000;

/**
 * 시세를 처음 연 뒤 몇 번까지 재촉할까.
 *
 * 시세는 pending 을 안 준다(있고 없고만 있다). 그래서 횟수로 끊는다 —
 * 끊지 않으면 시세가 영영 안 오는 종목 하나 때문에 4초마다 영원히
 * 두드리게 된다.
 */
export const 재촉_횟수 = 3;
