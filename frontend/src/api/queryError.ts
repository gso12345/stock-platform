/**
 * 조회가 실패했을 때 사용자에게 알리는 한 자리.
 *
 * useQuery 가 102개인데 isError 를 다루는 곳이 31개뿐이었다. 나머지
 * 70%는 실패해도 화면에 아무 표시가 없다 — 빈 목록이거나 영원한 로딩으로
 * 보인다. 사용자는 "느리다" 고 느끼지 "실패했다" 고 알지 못하고,
 * 그래서 새로고침도 안 해 본다.
 *
 * 100곳을 하나씩 고치는 대신 여기 한 곳에 둔다. React Query 의
 * QueryCache 는 모든 조회의 실패를 여기로 보낸다 — 새로 만드는 화면도
 * 저절로 포함된다.
 *
 * 화면 안쪽 표시(스켈레톤 자리에 "불러오지 못했습니다")를 대신하지는
 * 않는다. 그건 그 화면이 할 일이고, 여기는 '아무 말도 없는 것' 을
 * 막는 바닥이다.
 */

type 듣는이 = (메시지: string) => void;

let 듣는이들: 듣는이[] = [];

export function 오류구독(f: 듣는이): () => void {
  듣는이들.push(f);
  return () => { 듣는이들 = 듣는이들.filter((x) => x !== f); };
}

/** 같은 실패가 몰아칠 때 같은 말을 여러 번 띄우지 않는다.
 *
 *  서버가 자고 있으면 화면 하나가 대여섯 개를 한꺼번에 실패시킨다.
 *  그때마다 알림이 뜨면 화면이 알림으로 덮인다. */
let 마지막 = { 글: "", 때: 0 };
const 묶는시간 = 4000;

export function 조회실패알림(e: unknown): void {
  const 글 = 사람말로(e);
  if (!글) return;                       // 알릴 것이 없는 실패는 조용히 넘어간다
  const 지금 = Date.now();
  if (글 === 마지막.글 && 지금 - 마지막.때 < 묶는시간) return;
  마지막 = { 글, 때: 지금 };
  듣는이들.forEach((f) => f(글));
}

/** 서버가 뱉은 것을 사람이 읽는 문장으로.
 *
 *  예외 이름이나 상태 코드를 그대로 보여 주면 뜻이 없고, 서버 안쪽
 *  사정만 드러난다(지난번 보유비중에서 지적받은 그대로다). */
export function 사람말로(e: any): string {
  const 코드: number | undefined = e?.response?.status;

  // 로그인이 필요한 자리는 화면이 알아서 로그인으로 보낸다.
  // 여기서 또 알리면 두 번 말하는 셈이다
  if (코드 === 401 || 코드 === 403) return "";

  if (코드 === 404) return "";           // 없는 것을 물은 경우 — 화면이 빈 상태로 그린다
  if (코드 === 429) return "요청이 너무 잦습니다. 잠시 후 다시 시도해 주세요";
  if (코드 && 코드 >= 500) return "서버에 문제가 있어 불러오지 못했습니다";

  // 응답 자체가 없는 경우 — 끊겼거나, 서버가 자다 깨는 중이다
  if (e?.code === "ECONNABORTED" || /timeout/i.test(String(e?.message))) {
    return "응답이 늦어 불러오지 못했습니다. 잠시 후 다시 시도해 주세요";
  }
  if (!코드) {
    return navigator.onLine === false
      ? "인터넷 연결이 끊겼습니다"
      : "서버에 연결하지 못했습니다";
  }
  return "불러오지 못했습니다";
}

/** 검사에서 되돌리기 위한 것 */
export function _비우기(): void {
  마지막 = { 글: "", 때: 0 };
  듣는이들 = [];
}
