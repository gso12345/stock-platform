/**
 * 백테스트가 **정상 동작 중에 끊기지 않는가.**
 *
 * ── 무엇이 문제였나 ────────────────────────────────────────
 *
 * axios 상한이 30초 하나였다. 그런데 화면은 스스로 '자던 서버면 25초를
 * 더 잡아야 한다' 고 어림하고 있었다(AllocationTab 의 예상초). 즉 앱이
 * 자기 손으로 잰 시간과 자기 손으로 건 상한이 서로 어긋나 있었다 —
 *
 *     자산  5개  깨어있는 서버  7.2초 · 자던 서버 32.2초  ← 끊김
 *     자산 12개               9.4초 ·          34.4초  ← 끊김
 *     자산 20개              13.8초 ·          38.8초  ← 끊김
 *
 * 끊기면 화면에는 '서버에 연결하지 못했습니다' 가 떴다. 서버는 멀쩡히
 * 계산 중인데 고장으로 읽힌 것이다.
 *
 * 엔진 쪽에도 같은 기록이 남아 있다 — '계산만으로 23초가 걸려 화면의
 * 30초 시한을 넘기고 있었다(실측)'. 그때는 서버를 빠르게 만들어 피했을
 * 뿐, 상한 자체는 그대로였다.
 *
 * ── 여기서 못 박는 것 ──────────────────────────────────────
 *
 * 상한이 **화면이 어림하는 최악보다 넉넉해야 한다.** 숫자를 그냥 적어
 * 두면 나중에 어림이 늘거나 자산 상한이 올라갈 때 조용히 다시 끊긴다.
 * 그래서 예상초로 직접 재서 견준다.
 */
import { describe, it, expect } from "vitest";

import { 무거운상한 } from "../client";
import { 예상초 } from "@/components/backtest/AllocationTab";
import { 첫설정, 최대자산수 } from "@/components/backtest/AllocationForm";
import type { 배분자산 } from "../stocks";

/** 자산 n 개를 담고, 오래 걸리는 것은 다 켠 설정 */
function 최악설정(n: number) {
  const assets: 배분자산[] = Array.from({ length: n }, (_, i) => ({
    symbol: `S${i}`, market: "US", name: `S${i}`, weight: 100 / n,
  }));
  return {
    ...첫설정(),
    assets,
    currency: "KRW" as const,      // 달러 자산이라 환율도 받는다
    total_return: true,            // 배당도 받는다
    benchmark: "allweather" as const,  // 한 번 더 돌린다
  };
}


describe("백테스트 상한은 화면의 어림보다 넉넉하다", () => {
  it("자산을 꽉 채워도 상한 안에 든다", () => {
    const 최악 = 예상초(최악설정(최대자산수), true);   // true = 자던 서버
    expect(무거운상한 / 1000, `어림 ${최악.toFixed(1)}초인데 상한이 모자라다`)
      .toBeGreaterThan(최악);
  });

  it("어림의 두 배는 되게 둔다", () => {
    /* 어림은 어림이다. 야후가 느린 날이나 서버가 유난히 오래 자던
       날에는 그보다 더 걸린다. 딱 맞게 잡으면 그런 날마다 끊긴다. */
    const 최악 = 예상초(최악설정(최대자산수), true);
    expect(무거운상한 / 1000).toBeGreaterThanOrEqual(최악 * 2);
  });

  it("예전 30초로는 끊겼다 — 그 사실을 기록해 둔다", () => {
    /* 이 줄이 깨지면 어림이 크게 줄었다는 뜻이다. 그때는 상한을
       다시 생각해 봐도 된다. */
    const 자던서버 = 예상초(최악설정(5), true);
    expect(자던서버, "자산 5개짜리도 30초를 넘겼다는 전제가 깨졌다")
      .toBeGreaterThan(30);
  });

  it("깨어 있는 서버면 훨씬 빠르다 — 그래서 다시 누르라고 안내한다", () => {
    const 깨어있음 = 예상초(최악설정(최대자산수), false);
    const 자고있음 = 예상초(최악설정(최대자산수), true);
    expect(깨어있음).toBeLessThan(자고있음 / 2);
  });
});


describe("보통 요청까지 늘리지는 않는다", () => {
  it("무거운 상한은 보통 상한보다 훨씬 크다", () => {
    /* 목록·시세 같은 것은 오래 걸리면 뭔가 잘못된 것이라, 오래 붙잡고
       있느니 끊고 다시 묻는 편이 낫다. 전역으로 올리면 화면이 3분
       동안 뼈대만 보여 주는 일이 생긴다. */
    expect(무거운상한).toBeGreaterThan(30_000 * 3);
  });

  it("그래도 무한정은 아니다", () => {
    //: 정말 뭔가 잘못됐을 때 영원히 기다리면 안 된다
    expect(무거운상한).toBeLessThanOrEqual(300_000);
  });
});
