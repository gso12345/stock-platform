/**
 * 서버에서 받아 온 것들을 담아 두는 자리.
 *
 * 여기 담긴 것 중에는 "누가 보느냐" 에 따라 달라지는 값이 섞여 있다 —
 * 피드의 좋아요 여부, 내 자산, 관심종목, 알림 개수. 사람이 바뀌면 그것들은
 * 통째로 남의 것이 된다.
 *
 * 그래서 로그인·로그아웃 때 비운다. 예전에는 안 비워서 —
 *
 *   1) A 가 어떤 글에 좋아요를 누른다 (화면·서버 모두 눌린 상태)
 *   2) 로그아웃 → 다시 로그인. 서버 데이터 캐시는 그대로 남는다
 *   3) 피드를 열면 캐시된 옛 목록이 먼저 보인다(staleTime 2분)
 *   4) 거기서 좋아요를 누르면 화면은 "누름" 으로 바뀌는데,
 *      서버는 이미 눌려 있으니 취소로 처리한다
 *
 * 화면과 서버가 서로 반대가 되고, 그때부터 눌러도 안 눌러도 어긋난다 —
 * "중복으로 좋아요를 누를 수 있다" 는 것이 이 상태다.
 *
 * 이 파일이 따로 있는 이유는 authStore 가 이걸 부를 수 있어야 해서다.
 * main.tsx 안에 두면 화면 밖에서는 손댈 수 없다.
 */
import { QueryClient, QueryCache } from "@tanstack/react-query";
import { 조회실패알림 } from "./queryError";
import { 최근조회정리 } from "@/utils/recentlyViewed";
import { 되살리기, 붙이기 } from "./queryPersist";

export const queryClient = new QueryClient({
  /* 조회가 실패하면 여기로 온다.
     useQuery 102개 중 isError 를 다루는 곳이 31개뿐이라, 나머지는
     실패해도 화면에 아무 표시가 없었다 — 빈 목록이거나 영원한 로딩으로
     보여서 사용자는 "느리다" 고만 느꼈다. 100곳을 하나씩 고치는 대신
     한 자리에 둔다. 새로 만드는 화면도 저절로 포함된다. */
  queryCache: new QueryCache({
    onError: (e) => 조회실패알림(e),
  }),
  defaultOptions: {
    queries: {
      staleTime: 300_000,
      gcTime: 1_800_000,
      refetchOnWindowFocus: false,
      /* 다시 시도하는 규칙.
       *
       * 예전에는 3번을 2초·6초·18초 간격으로 했다. Render 무료 플랜이
       * 자다 깨는 데 20~45초가 걸려서, 그동안 버티라고 잡은 값이다.
       * 그 잠듦이 없어졌으므로 이 값은 이제 순수한 지연이다 —
       * 한 번 삐끗하면 화면이 26초 동안 아무 말 없이 멈춘다.
       *
       * 그리고 4xx 는 아예 다시 안 한다. 로그인이 안 됐거나(401),
       * 없는 것을 찾거나(404), 값이 틀린(422) 요청은 몇 번을 더 보내도
       * 같은 답이 온다. 그런데도 세 번을 26초에 걸쳐 보내고 있었다 —
       * 로그아웃 상태로 앱을 여는 사람이 정확히 그 상황이다. */
      retry: (횟수, 오류) => {
        const 상태 = (오류 as { response?: { status?: number } })?.response?.status;
        if (typeof 상태 === "number" && 상태 >= 400 && 상태 < 500) return false;
        return 횟수 < 2;
      },
      retryDelay: (attempt) => Math.min(400 * 3 ** attempt, 3_000),
    },
  },
});

/** 사람이 바뀌었다 — 받아 둔 것을 전부 버린다.
 *
 *  좋아요만의 문제가 아니다. 내 자산·관심종목·알림도 앞사람 것이 남는다.
 *  일부만 골라 지우면 빠뜨린 것이 반드시 생기므로 통째로 버린다. */
/* 지난번에 받아 둔 것을 곧바로 화면에 올린다.
   화면(main.tsx)이 그려지기 전에 해야 뜻이 있다 — 그려진 뒤에 넣으면
   이미 뼈대를 한 번 보여 준 뒤다. 그래서 이 파일에서 바로 부른다. */
되살리기(queryClient);
붙이기(queryClient);

export function 사용자바뀜() {
  queryClient.clear();
  /* 서버에서 받아 온 것 말고, 브라우저에 직접 쌓아 둔 것도 앞사람 것이 남는다.
     최근 본 종목이 그렇다 — 공용 기기에서 무엇을 들여다봤는지가 다음 사람에게
     그대로 넘어갔다. 지금은 사람별로 칸을 나눴고, 여기서는 칸을 나누기 전에
     쌓인 공용 기록을 치운다. */
  최근조회정리();
}
