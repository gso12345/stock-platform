/**
 * 서버에서 받아 온 것들을 담아 두는 자리.
 *
 * 여기 담긴 것 중에는 "누가 보느냐" 에 따라 달라지는 값이 섞여 있다 —
 * 피드의 좋아요 여부, 내 자산, 관심종목, 알림 개수. 사람이 바뀌면 그것들은
 * 통째로 남의 것이 된다.
 *
 * 그래서 로그인·로그아웃 때 비운다. 예전에는 안 비워서 —
 *
 *   1) A 가 어떤 글에 좋아요를 누른다 (화면·서버 모두 눌린 상태)
 *   2) 로그아웃 → 다시 로그인. 서버 데이터 캐시는 그대로 남는다
 *   3) 피드를 열면 캐시된 옛 목록이 먼저 보인다(staleTime 2분)
 *   4) 거기서 좋아요를 누르면 화면은 "누름" 으로 바뀌는데,
 *      서버는 이미 눌려 있으니 취소로 처리한다
 *
 * 화면과 서버가 서로 반대가 되고, 그때부터 눌러도 안 눌러도 어긋난다 —
 * "중복으로 좋아요를 누를 수 있다" 는 것이 이 상태다.
 *
 * 이 파일이 따로 있는 이유는 authStore 가 이걸 부를 수 있어야 해서다.
 * main.tsx 안에 두면 화면 밖에서는 손댈 수 없다.
 */
import { QueryClient } from "@tanstack/react-query";

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 300_000,
      gcTime: 1_800_000,
      refetchOnWindowFocus: false,
      // Render 무료 플랜 슬립(20~45s) 대응: 3회 재시도, 지수 백오프(2s→6s→18s)
      retry: 3,
      retryDelay: (attempt) => Math.min(2_000 * 3 ** attempt, 20_000),
    },
  },
});

/** 사람이 바뀌었다 — 받아 둔 것을 전부 버린다.
 *
 *  좋아요만의 문제가 아니다. 내 자산·관심종목·알림도 앞사람 것이 남는다.
 *  일부만 골라 지우면 빠뜨린 것이 반드시 생기므로 통째로 버린다. */
export function 사용자바뀜() {
  queryClient.clear();
}
